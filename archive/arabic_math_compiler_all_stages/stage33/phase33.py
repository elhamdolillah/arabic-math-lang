print("   ﴿سبع سماوات طباقاً﴾ — الدرجة الثالثة")
print("   ﴿فمن يعمل مثقال ذرة خيراً يره﴾ — قاعدة الضرب")
print("   ﴿ثم استوى إلى السماء وهي دخان﴾ — المشتقة الثانية")
