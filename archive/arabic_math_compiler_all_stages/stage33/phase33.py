#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
المرحلة 33: التفاضل الرمزي (فرع)
الدستور: ﴿أصلها ثابت وفرعها في السماء﴾
"""
import sys, subprocess
sys.path.insert(0, '.')
from math_complete import *

# ═══════════════════════════════════════════════════════════
print("=" * 70)
print("المرحلة 33: التفاضل الرمزي (فرع)")
print("الدستور: ﴿أصلها ثابت وفرعها في السماء﴾")
print("=" * 70)

failed = 0

# ─────────────────────────────────────────────────────────
# اختبار 1: مشتقة كثير حدود من الدرجة 2
# ─────────────────────────────────────────────────────────
print("\n🧪 اختبار 1: مشتقة الدرجة 2 (﴿أصلها ثابت وفرعها في السماء﴾)")
برنامج_مشتقة2 = """أ ≔ 3
ب ≔ 2
ج ≔ 1
مشتقة_أ ≔ 2 · أ
مشتقة_ب ≔ ب
⎕ "f(x) = 3x² + 2x + 1"
⎕ "f'(x) = " ⊕ نص(مشتقة_أ) ⊕ "x + " ⊕ نص(مشتقة_ب)
"""

ر = حلل_رموز(برنامج_مشتقة2)
ب = حلل_برنامج(ر)
asm = compile_program(ب)
with open('calc1.asm', 'w') as f:
    f.write(asm)
subprocess.run(['nasm', '-f', 'elf64', 'calc1.asm', '-o', 'calc1.o'], check=True)
subprocess.run(['ld', 'calc1.o', '-o', 'calc1'], check=True)
result = subprocess.run(['./calc1'], capture_output=True, text=True)
out = result.stdout.strip()
print(f"  الخرج:\n{out}")

if "f'(x) = 6x + 2" in out:
    print("  ✅ مشتقة الدرجة 2 تعمل!")
else:
    print("  ❌ فشل")
    failed += 1

# ─────────────────────────────────────────────────────────
# اختبار 2: قيمة المشتقة عند نقطة
# ─────────────────────────────────────────────────────────
print("\n🧪 اختبار 2: قيمة المشتقة عند نقطة (﴿تؤتي أكلها كل حين﴾)")
برنامج_قيمة = """أ ≔ 3
ب ≔ 2
ج ≔ 1
مشتقة_أ ≔ 2 · أ
مشتقة_ب ≔ ب
نقطة ≔ 1
قيمة_١ ≔ مشتقة_أ · نقطة + مشتقة_ب
نقطة ≔ 2
قيمة_٢ ≔ مشتقة_أ · نقطة + مشتقة_ب
نقطة ≔ 5
قيمة_٥ ≔ مشتقة_أ · نقطة + مشتقة_ب
⎕ "f'(1) = " ⊕ نص(قيمة_١)
⎕ "f'(2) = " ⊕ نص(قيمة_٢)
⎕ "f'(5) = " ⊕ نص(قيمة_٥)
"""

ر = حلل_رموز(برنامج_قيمة)
ب = حلل_برنامج(ر)
asm = compile_program(ب)
with open('calc2.asm', 'w') as f:
    f.write(asm)
subprocess.run(['nasm', '-f', 'elf64', 'calc2.asm', '-o', 'calc2.o'], check=True)
subprocess.run(['ld', 'calc2.o', '-o', 'calc2'], check=True)
result = subprocess.run(['./calc2'], capture_output=True, text=True)
out = result.stdout.strip()
print(f"  الخرج:\n{out}")

if "f'(1) = 8" in out and "f'(2) = 14" in out and "f'(5) = 32" in out:
    print("  ✅ قيمة المشتقة عند نقطة تعمل!")
else:
    print("  ❌ فشل")
    failed += 1

# ─────────────────────────────────────────────────────────
# اختبار 3: مشتقة كثير حدود من الدرجة 3
# ─────────────────────────────────────────────────────────
print("\n🧪 اختبار 3: مشتقة الدرجة 3 (﴿سبع سماوات طباقاً﴾)")
برنامج_مشتقة3 = """أ ≔ 1
ب ≔ 2
ج ≔ 3
د ≔ 4
مشتقة_أ ≔ 3 · أ
مشتقة_ب ≔ 2 · ب
مشتقة_ج ≔ ج
⎕ "f(x) = x³ + 2x² + 3x + 4"
⎕ "f'(x) = " ⊕ نص(مشتقة_أ) ⊕ "x² + " ⊕ نص(مشتقة_ب) ⊕ "x + " ⊕ نص(مشتقة_ج)
نقطة ≔ 1
قيمة ≔ مشتقة_أ · نقطة · نقطة + مشتقة_ب · نقطة + مشتقة_ج
⎕ "f'(1) = " ⊕ نص(قيمة)
نقطة ≔ 2
قيمة ≔ مشتقة_أ · نقطة · نقطة + مشتقة_ب · نقطة + مشتقة_ج
⎕ "f'(2) = " ⊕ نص(قيمة)
"""

ر = حلل_رموز(برنامج_مشتقة3)
ب = حلل_برنامج(ر)
asm = compile_program(ب)
with open('calc3.asm', 'w') as f:
    f.write(asm)
subprocess.run(['nasm', '-f', 'elf64', 'calc3.asm', '-o', 'calc3.o'], check=True)
subprocess.run(['ld', 'calc3.o', '-o', 'calc3'], check=True)
result = subprocess.run(['./calc3'], capture_output=True, text=True)
out = result.stdout.strip()
print(f"  الخرج:\n{out}")

if "f'(x) = 3x² + 4x + 3" in out and "f'(1) = 10" in out and "f'(2) = 23" in out:
    print("  ✅ مشتقة الدرجة 3 تعمل!")
else:
    print("  ❌ فشل")
    failed += 1

# ─────────────────────────────────────────────────────────
# اختبار 4: قاعدة الضرب (f·g)' = f'·g + f·g'
# ─────────────────────────────────────────────────────────
print("\n🧪 اختبار 4: قاعدة الضرب (﴿فمن يعمل مثقال ذرة خيراً يره﴾)")
برنامج_ضرب = """و ≔ 3
ز ≔ 2
مشتقة_و ≔ 2 · و
مشتقة_ز ≔ ز
نقطة ≔ 1
قيمة_و ≔ و · نقطة
قيمة_ز ≔ ز
مشتقة_حاصل ≔ مشتقة_و · نقطة · قيمة_ز + قيمة_و · مشتقة_ز
⎕ "f(x) = 3x², g(x) = 2x"
⎕ "(f·g)'(1) = f'(1)·g(1) + f(1)·g'(1)"
⎕ "= " ⊕ نص(مشتقة_و · نقطة) ⊕ "·" ⊕ نص(قيمة_ز) ⊕ " + " ⊕ نص(قيمة_و) ⊕ "·" ⊕ نص(مشتقة_ز)
⎕ "= " ⊕ نص(مشتقة_حاصل)
"""

ر = حلل_رموز(برنامج_ضرب)
ب = حلل_برنامج(ر)
asm = compile_program(ب)
with open('calc4.asm', 'w') as f:
    f.write(asm)
subprocess.run(['nasm', '-f', 'elf64', 'calc4.asm', '-o', 'calc4.o'], check=True)
subprocess.run(['ld', 'calc4.o', '-o', 'calc4'], check=True)
result = subprocess.run(['./calc4'], capture_output=True, text=True)
out = result.stdout.strip()
print(f"  الخرج:\n{out}")

# f(x)=3x², g(x)=2x, f·g=6x³, (f·g)'=18x², (f·g)'(1)=18
if "= 18" in out:
    print("  ✅ قاعدة الضرب تعمل!")
else:
    print("  ❌ فشل")
    failed += 1

# ─────────────────────────────────────────────────────────
# اختبار 5: المشتقة الثانية (التسارع)
# ─────────────────────────────────────────────────────────
print("\n🧪 اختبار 5: المشتقة الثانية (﴿ثم استوى إلى السماء وهي دخان﴾)")
برنامج_ثانية = """أ ≔ 3
ب ≔ 2
ج ≔ 1
مشتقة_أولى_أ ≔ 2 · أ
مشتقة_أولى_ب ≔ ب
مشتقة_ثانية ≔ مشتقة_أولى_أ
⎕ "f(x) = 3x² + 2x + 1"
⎕ "f'(x) = 6x + 2"
⎕ "f''(x) = " ⊕ نص(مشتقة_ثانية)
⎕ "المشتقة الثانية ثابتة = التسارع"
"""

ر = حلل_رموز(برنامج_ثانية)
ب = حلل_برنامج(ر)
asm = compile_program(ب)
with open('calc5.asm', 'w') as f:
    f.write(asm)
subprocess.run(['nasm', '-f', 'elf64', 'calc5.asm', '-o', 'calc5.o'], check=True)
subprocess.run(['ld', 'calc5.o', '-o', 'calc5'], check=True)
result = subprocess.run(['./calc5'], capture_output=True, text=True)
out = result.stdout.strip()
print(f"  الخرج:\n{out}")

if "f''(x) = 6" in out:
    print("  ✅ المشتقة الثانية تعمل!")
else:
    print("  ❌ فشل")
    failed += 1

# ─────────────────────────────────────────────────────────
# اختبار 6: حفظ النتائج في ملف
# ─────────────────────────────────────────────────────────
print("\n🧪 اختبار 6: حفظ النتائج (﴿في إمام مبين﴾)")
برنامج_حفظ = """ملف ≔ فتح("calculus.txt")
اكتب_ملف(ملف، "f(x)=3x^2+2x+1")
اكتب_ملف(ملف، " f'(x)=6x+2")
اكتب_ملف(ملف، " f''(x)=6")
اكتب_ملف(ملف، " f'(1)=8 f'(2)=14")
اختم(ملف)
ملف ≔ فتح("calculus.txt")
محتوى ≔ اقرأ_ملف(ملف، 4096)
اختم(ملف)
⎕ محتوى
"""

ر = حلل_رموز(برنامج_حفظ)
ب = حلل_برنامج(ر)
asm = compile_program(ب)
with open('calc6.asm', 'w') as f:
    f.write(asm)
subprocess.run(['nasm', '-f', 'elf64', 'calc6.asm', '-o', 'calc6.o'], check=True)
subprocess.run(['ld', 'calc6.o', '-o', 'calc6'], check=True)
result = subprocess.run(['./calc6'], capture_output=True, text=True)
out = result.stdout.strip()
print(f"  الخرج: {out}")

if "f(x)=3x^2+2x+1" in out and "f'(x)=6x+2" in out and "f''(x)=6" in out:
    print("  ✅ حفظ النتائج يعمل!")
else:
    print("  ❌ فشل")
    failed += 1

