    print(f"   - مشتقة كثير حدود من الدرجة 3")
    print(f"   - قاعدة الضرب (f·g)' = f'·g + f·g'")
    print(f"   - المشتقة الثانية (التسارع)")
    print(f"   - حفظ النتائج في ملف")
    print(f"\n   الخطوة التالية: المرحلة 34 — التكامل الرمزي (جمع)")
