# -*- coding: utf-8 -*-
import sys

# ============================================================
# مقبض الذاكرة
# في النواة النهائية سيكون مؤشرًا أو إزاحة داخل Arena
# ============================================================
class مقبض:
    def __init__(self, معرف, نوع_الحامل, بيانات):
        self.معرف = معرف
        self.نوع = نوع_الحامل
        self.بيانات = بيانات
        self.حي = True

# ============================================================
# مدير الذاكرة
# ============================================================
class مدير_الذاكرة:
    def __init__(self):
        self.مقابض = {}
        self.معرف_تال = 1

    def خصص_مصفوفة_صحيح(self, قيم):
        م = مقبض(self.معرف_تال, "مصفوفة_صحيح", list(قيم))
        self.مقابض[م.معرف] = م
        self.معرف_تال += 1
        return م.معرف

    def اجلب_مقبض_حي(self, معرف):
        if معرف not in self.مقابض:
            raise Exception("مقبض غير موجود أو تم نقله بطريقة غير صحيحة.")
        م = self.مقابض[معرف]
        if not م.حي:
            raise Exception("مقبض محرر.")
        return م

    def حرر(self, معرف):
        م = self.اجلب_مقبض_حي(معرف)
        م.حي = False
        return م

def اعرض_خريطة_الذاكرة(ذاكرة):
    print("--- خريطة الذاكرة النهائية ---")
    for معرف, م in ذاكرة.مقابض.items():
        حالة = "حي" if م.حي else "محرر"
        طول = len(م.بيانات)
        print(f"مقبض#{معرف} {م.نوع} طول={طول} حالة={حالة}")

# ============================================================
# مدقق الملكية
# يمنع:
# - استخدام بعد النقل
# - استخدام بعد التحرير
# - تحرير مزدوج
# - تسريب ذاكرة
# ============================================================
def دقق_ملكية(برنامج):
    حالة = {}

    def تطلب_مملوك(متغير):
        if متغير not in حالة:
            raise Exception(f"خطأ ملكية: المتغير '{متغير}' غير معرف.")

        وضع = حالة[متغير]

        if وضع == "منقول":
            raise Exception(f"خطأ ملكية: '{متغير}' نُقل ولا يمكن استخدامه بعد النقل.")

        if وضع == "محرر":
            raise Exception(f"خطأ ملكية: '{متغير}' محرر ولا يمكن استخدامه.")

        if وضع != "مملوك":
            raise Exception(f"خطأ ملكية: '{متغير}' ليس كائناً مملوكاً.")

    for بيان in برنامج:
        الأمر = بيان[0]

        if الأمر == "خصص_مصفوفة":
            متغير = بيان[1]

            if حالة.get(متغير) == "مملوك":
                raise Exception(f"تسريب ذاكرة: '{متغير}' يملك مقبضاً بالفعل قبل التخصيص الجديد.")

            حالة[متغير] = "مملوك"

        elif الأمر == "اسند_رقم":
            متغير = بيان[1]

            if حالة.get(متغير) == "مملوك":
                raise Exception(f"تسريب ذاكرة: '{متغير}' يملك مقبضاً ولا يمكن استبداله برقم دون تحرير.")

            حالة[متغير] = "بدائي"

        elif الأمر == "اطبع_رقم":
            متغير = بيان[1]

            if حالة.get(متغير) != "بدائي":
                raise Exception(f"خطأ أنواع/ملكية: '{متغير}' ليس رقماً بدائياً.")

        elif الأمر == "اطبع_طول":
            تطلب_مملوك(بيان[1])

        elif الأمر == "اطبع_عنصر":
            تطلب_مملوك(بيان[1])

        elif الأمر == "اكتب_عنصر":
            تطلب_مملوك(بيان[1])

        elif الأمر == "انقل":
            الهدف = بيان[1]
            المصدر = بيان[2]

            تطلب_مملوك(المصدر)

            if حالة.get(الهدف) == "مملوك":
                raise Exception(f"تسريب ذاكرة: '{الهدف}' يملك مقبضاً بالفعل قبل النقل إليه.")

            حالة[الهدف] = "مملوك"
            حالة[المصدر] = "منقول"

        elif الأمر == "حرر":
            متغير = بيان[1]

            تطلب_مملوك(متغير)

            حالة[متغير] = "محرر"

        else:
            raise Exception(f"أمر غير معروف في تدقيق الملكية: {الأمر}")

    # منع تسريب الذاكرة في نهاية البرنامج
    for متغير, وضع in حالة.items():
        if وضع == "مملوك":
            raise Exception(f"تسريب ذاكرة: '{متغير}' ما زال يملك مقبضاً في نهاية البرنامج.")

    print("✅ نجح تدقيق الملكية.")

# ============================================================
# التنفيذ الفعلي
# ============================================================
def نفذ_برنامج(برنامج):
    ذاكرة = مدير_الذاكرة()
    بيئة = {}

    for بيان in برنامج:
        الأمر = بيان[0]

        if الأمر == "خصص_مصفوفة":
            متغير = بيان[1]
            قيم = بيان[2]

            معرف = ذاكرة.خصص_مصفوفة_صحيح(قيم)
            بيئة[متغير] = معرف

            print(f"✅ تم تخصيص مقبض#{معرف}: مصفوفة_صحيح طول={len(قيم)}")

        elif الأمر == "اسند_رقم":
            متغير = بيان[1]
            قيمة = بيان[2]
            بيئة[متغير] = قيمة

        elif الأمر == "اطبع_رقم":
            متغير = بيان[1]
            sys.stdout.write(str(بيئة[متغير]) + "\n")

        elif الأمر == "اطبع_طول":
            متغير = بيان[1]
            م = ذاكرة.اجلب_مقبض_حي(بيئة[متغير])
            sys.stdout.write(str(len(م.بيانات)) + "\n")

        elif الأمر == "اطبع_عنصر":
            متغير = بيان[1]
            فهرس = بيان[2]
            م = ذاكرة.اجلب_مقبض_حي(بيئة[متغير])
            sys.stdout.write(str(م.بيانات[فهرس]) + "\n")

        elif الأمر == "اكتب_عنصر":
            متغير = بيان[1]
            فهرس = بيان[2]
            قيمة = بيان[3]
            م = ذاكرة.اجلب_مقبض_حي(بيئة[متغير])
            م.بيانات[فهرس] = قيمة

        elif الأمر == "انقل":
            الهدف = بيان[1]
            المصدر = بيان[2]

            if المصدر not in بيئة or بيئة[المصدر] is None:
                raise Exception(f"خطأ تنفيذي: '{المصدر}' لا يحمل مقبضاً حياً.")

            بيئة[الهدف] = بيئة[المصدر]
            بيئة[المصدر] = None

        elif الأمر == "حرر":
            متغير = بيان[1]
            معرف = بيئة[متغير]
            م = ذاكرة.حرر(معرف)
            بيئة[متغير] = None
            print(f"♻️ تم تحرير مقبض#{م.معرف}")

        else:
            raise Exception(f"أمر غير معروف في التنفيذ: {الأمر}")

    return ذاكرة

# ============================================================
# إطار الاختبار
# ============================================================
نتائج_الاختبار = []

def اختبر(اسم, برنامج, يجب_نجاح):
    print(f"\n[اختبار: {اسم}]")

    try:
        دقق_ملكية(برنامج)
        ذاكرة = نفذ_برنامج(برنامج)

        if يجب_نجاح:
            اعرض_خريطة_الذاكرة(ذاكرة)
            نتائج_الاختبار.append(True)
        else:
            print("❌ كان يجب أن يفشل هذا الاختبار.")
            نتائج_الاختبار.append(False)

    except Exception as e:
        if يجب_نجاح:
            print(f"❌ فشل غير متوقع: {e}")
            نتائج_الاختبار.append(False)
        else:
            print(f"✅ تم اعتراض الخطأ: {e}")
            نتائج_الاختبار.append(True)

