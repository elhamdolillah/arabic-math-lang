# -*- coding: utf-8 -*-
import sys

# ============================================================
# مولد شفرة x86_64 Assembly
# ============================================================
class مولد_x86_64:
    def __init__(self):
        self.كود = []
        self.بيانات = []
        self.عناوين_النصوص = {}
        self.عداد_النصوص = 0
        
    def أضف_تعليمة(self, تعليمة):
        self.كود.append(تعليمة)
        
    def أضف_بيانات(self, بيانات):
        self.بيانات.append(بيانات)
        
    def أنشئ_نص(self, نص):
        """يخزن نصاً في قسم البيانات ويعيد اسمه"""
        اسم = f"msg_{self.عداد_النصوص}"
        self.عداد_النصوص += 1
        # تحويل النص إلى بايتات UTF-8
        بايتات = نص.encode('utf-8')
        بايتات_str = ','.join([f'0x{b:02x}' for b in بايتات])
        self.أضف_بيانات(f"{اسم}:")
        self.أضف_بيانات(f"    .byte {بايتات_str}")
        self.أضف_بيانات(f"{اسم}_len = . - {اسم}")
        return اسم, len(بايتات)
        
    def ولّد_برنامج(self, برنامج):
        """يولد كود Assembly لبرنامج كامل"""
        
        # رأس الملف
        self.أضف_تعليمة(".section .data")
        
        # نصوص ثابتة
        اسم_نجاح, _ = self.أنشئ_نص("✅ تم التنفيذ بنجاح\n")
        
        self.أضف_تعليمة("")
        self.أضف_تعليمة(".section .text")
        self.أضف_تعليمة(".globl _start")
        self.أضف_تعليمة("")
        self.أضف_تعليمة("_start:")
        
        # تنفيذ البرنامج
        for بيان in برنامج:
            self.ولّد_بيان(بيان)
            
        # طباعة رسالة النجاح
        self.أضف_تعليمة(f"    # طباعة رسالة النجاح")
        self.أضف_تعليمة(f"    mov $1, %rax          # sys_write")
        self.أضف_تعليمة(f"    mov $1, %rdi          # stdout")
        self.أضف_تعليمة(f"    lea {اسم_نجاح}(%rip), %rsi")
        self.أضف_تعليمة(f"    mov ${اسم_نجاح}_len, %rdx")
        self.أضف_تعليمة(f"    syscall")
        
        # الخروج
        self.أضف_تعليمة(f"    # sys_exit")
        self.أضف_تعليمة(f"    mov $60, %rax")
        self.أضف_تعليمة(f"    xor %rdi, %rdi")
        self.أضف_تعليمة(f"    syscall")
        
    def ولّد_بيان(self, بيان):
        الأمر = بيان[0]
        
        if الأمر == "اطبع_نص":
            نص = بيان[1]
            اسم, طول = self.أنشئ_نص(نص)
            self.أضف_تعليمة(f"    # اطبع: {نص}")
            self.أضف_تعليمة(f"    mov $1, %rax          # sys_write")
            self.أضف_تعليمة(f"    mov $1, %rdi          # stdout")
            self.أضف_تعليمة(f"    lea {اسم}(%rip), %rsi")
            self.أضف_تعليمة(f"    mov ${طول}, %rdx")
            self.أضف_تعليمة(f"    syscall")
            
        elif الأمر == "اسند_رقم":
            متغير = بيان[1]
            قيمة = بيان[2]
            # في النسخة المبسطة، نخزن الرقم في register
            self.أضف_تعليمة(f"    # اسند {متغير} = {قيمة}")
            self.أضف_تعليمة(f"    mov ${قيمة}, %rbx")
            
        elif الأمر == "اطبع_رقم":
            # طباعة الرقم من rbx
            self.أضف_تعليمة(f"    # اطبع رقم من rbx")
            self.أضف_تعليمة(f"    # (تنفيذ مبسط: نحول الرقم إلى نص و نطبعه)")
            # هذا يحتاج دالة مساعدة، سنبسطها الآن
            self.أضف_تعليمة(f"    mov $1, %rax          # sys_write")
            self.أضف_تعليمة(f"    mov $1, %rdi          # stdout")
            self.أضف_تعليمة(f"    # تبسيط: نطبع '5' ثابتة الآن")
            
        elif الأمر == "مخصص":
            self.أضف_تعليمة(f"    # {بيان[1]}")
            
    def أكتب_ملف(self, اسم_الملف):
        with open(اسم_الملف, 'w') as f:
            # قسم البيانات أولاً
            for سطر in self.بيانات:
                f.write(سطر + '\n')
            f.write('\n')
            # ثم قسم الكود
            for سطر in self.كود:
                f.write(سطر + '\n')

# ============================================================
