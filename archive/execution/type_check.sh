# -*- coding: utf-8 -*-
import sys

# ============================================================
# ١. الأنواع الأساسية في النواة (Core Types)
# ============================================================
class نوع:
    صحيح = "صحيح"
    نص = "نص"
    فراغ = "فراغ"

# ============================================================
# ٢. عقود العمليات الموحدة (Operation Signatures)
# النواة لا تعرف "الجمع" للنصوص. النصوص لها "لصق".
# الصيغة: (نوع_اليسار, نوع_اليمين, نوع_النتيجة)
# ============================================================
عقود_العمليات = {
    "أضف": (نوع.صحيح, نوع.صحيح, نوع.صحيح),   
    "اطرح": (نوع.صحيح, نوع.صحيح, نوع.صحيح),
    "ألصق": (نوع.نص, نوع.نص, نوع.نص),          # عملية مخصصة للنصوص فقط
}

# بيئة الأنواع (Type Environment) - تحفظ نوع كل متغير
بيئة_الأنواع = {}

# ============================================================
# ٣. مدقق الأنواع (Type Verifier)
# ============================================================
def دقق_تعبير(تعبير):
    """يعيد نوع التعبير، أو يرمي خطأ إذا كان النوع غير متطابق"""
    الرأس = تعبير[0]
    
    if الرأس == "قيمة_صحيحة":
        return نوع.صحيح
        
    if الرأس == "قيمة_نصية":
        return نوع.نص
        
    if الرأس == "متغير":
        اسم = تعبير[1]
        if اسم not in بيئة_الأنواع:
            raise Exception(f"خطأ دلالي: المتغير '{اسم}' غير معرف.")
        return بيئة_الأنواع[اسم]
        
    if الرأس in عقود_العمليات:
        يسار_نوع = دقق_تعبير(تعبير[1])
        يمين_نوع = دقق_تعبير(تعبير[2])
        
        عقد = عقود_العمليات[الرأس]
        نوع_اليسار_المتوقع, نوع_اليمين_المتوقع, نوع_النتيجة = عقد
        
        # الصارم: إذا لم يتطابق النوعان، نوقف الترجمة فوراً
        if يسار_نوع != نوع_اليسار_المتوقع or يمين_نوع != نوع_اليمين_المتوقع:
            raise Exception(
                f"خطأ في الأنواع: العملية '{الرأس}' تتطلب ({نوع_اليسار_المتوقع}, {نوع_اليمين_المتوقع}) "
                f"ولكن تلقت ({يسار_نوع}, {يمين_نوع})."
            )
        return نوع_النتيجة
        
    raise Exception(f"عملية غير معروفة في النواة: {الرأس}")

def دقق_بيان(بيان):
    الرأس = بيان[0]
    
    if الرأس == "اسند":
        اسم = بيان[1]
        تعبير = بيان[2]
        نوع_التعبير = دقق_تعبير(تعبير)
        بيئة_الأنواع[اسم] = نوع_التعبير
        return نوع.فراغ
        
    if الرأس == "اطبع":
        دقق_تعبير(بيان[1])
        return نوع.فراغ
        
    raise Exception(f"بيان غير معروف: {الرأس}")

def دقق_برنامج(برنامج):
    print("--- بدء تدقيق الأنواع (Type Checking) ---")
    for بيان in برنامج:
        دقق_بيان(بيان)
    print("✅ نجح تدقيق الأنواع. الشفرة آمنة للتنفيذ على الآلة.")

# ============================================================
# ٤. الاختبارات المعمارية
# ============================================================

# [اختبار 1: برنامج صحيح] جمع رقمين
print("\n[اختبار 1: جمع رقمين]")
برنامج_صحيح = [
    ("اسند", "س", ("قيمة_صحيحة", 5)),
    ("اسند", "ص", ("قيمة_صحيحة", 10)),
    ("اسند", "مجموع", ("أضف", ("متغير", "س"), ("متغير", "ص"))),
    ("اطبع", ("متغير", "مجموع"))
]

try:
    بيئة_الأنواع.clear()
    دقق_برنامج(برنامج_صحيح)
except Exception as e:
    print(f"❌ فشل: {e}")


# [اختبار 2: برنامج خاطئ] محاولة جمع رقم مع نص
# هذا ما يمنع التحميل الزائد (Overloading) ويوحد النواة.
print("\n[اختبار 2: محاولة جمع رقم مع نص (يجب أن يرفضه المدقق)]")
برنامج_خاطئ = [
    ("اسند", "س", ("قيمة_صحيحة", 5)),
    ("اسند", "نص", ("قيمة_نصية", "سلام")),
    # محاولة استخدام 'أضف' مع نص ورقم -> يجب أن يرفضه المدقق
    ("اسند", "نتيجة", ("أضف", ("متغير", "س"), ("متغير", "نص")))
]

try:
    بيئة_الأنواع.clear()
    دقق_برنامج(برنامج_خاطئ)
except Exception as e:
    print(f"❌ تم اعتراض الخطأ بنجاح: {e}")


# [اختبار 3: الاستخدام الصحيح للنصوص] عملية 'ألصق'
print("\n[اختبار 3: لصق نصين]")
برنامج_لصق = [
    ("اسند", "ت1", ("قيمة_نصية", "مرحباً ")),
    ("اسند", "ت2", ("قيمة_نصية", "بك")),
    ("اسند", "جملة", ("ألصق", ("متغير", "ت1"), ("متغير", "ت2"))),
    ("اطبع", ("متغير", "جملة"))
]

try:
    بيئة_الأنواع.clear()
    دقق_برنامج(برنامج_لصق)
except Exception as e:
    print(f"❌ فشل: {e}")

PY

python3 type_verifier.py