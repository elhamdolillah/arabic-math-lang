#!/bin/sh
set -u

info() {
    printf '[%s] %s\n' "$1" "$2" >&2
}

# ============================================================
# الطبقة الأولى: إقلاع Assembly خام x86_64 Linux بدون libc
# ============================================================

if command -v as >/dev/null 2>&1 && command -v ld >/dev/null 2>&1; then
    info info "أحاول بناء إقلاع Assembly الخام..."

    cat > boot_ar.s <<'ASM'
.section .data

# سلام\n بالترميز UTF-8
# س = D8 B3
# ل = D9 84
# ا = D8 A7
# م = D9 85
# \n = 0A
msg:
    .byte 0xd8,0xb3,0xd9,0x84,0xd8,0xa7,0xd9,0x85,0x0a
msg_len = . - msg

# مخزن مؤقت لطباعة العدد
buf:
    .skip 32

.section .text
.globl _start

_start:
    # -----------------------------
    # نظام.اكتب stdout
    # -----------------------------
    mov $1, %rax          # sys_write
    mov $1, %rdi          # stdout
    lea msg(%rip), %rsi
    mov $msg_len, %rdx
    syscall

    # -----------------------------
    # عدد.أضف
    # 2 + 3
    # -----------------------------
    mov $2, %rbx
    mov $3, %rcx
    add %rcx, %rbx        # rbx = 5

    # -----------------------------
    # عدد.إلى_نص + نظام.اكتب
    # طباعة rbx ثم newline
    # -----------------------------
    lea buf(%rip), %rsi
    add $31, %rsi
    movb $0x0a, (%rsi)    # newline في نهاية المخزن
    mov %rsi, %r8         # مؤشر النهاية

    mov %rbx, %rax
    mov $10, %rcx

convert:
    xor %edx, %edx
    div %rcx
    add $0x30, %dl
    dec %rsi
    mov %dl, (%rsi)
    test %rax, %rax
    jnz convert

    # طول = مؤشر النهاية - مؤشر البداية + 1
    mov %r8, %rdx
    sub %rsi, %rdx
    add $1, %rdx

    mov $1, %rax          # sys_write
    mov $1, %rdi          # stdout
    syscall

    # -----------------------------
    # نظام.اخرج
    # -----------------------------
    mov $60, %rax         # sys_exit
    xor %rdi, %rdi
    syscall
ASM

    if as boot_ar.s -o boot_ar.o 2>/dev/null && ld boot_ar.o -o boot_ar 2>/dev/null; then
        if ./boot_ar; then
            exit 0
        else
            info warn "فشل تشغيل ناتج Assembly، سأنتقل إلى المحاكي."
        fi
    else
        info warn "فشل تجميع أو ربط Assembly، سأنتقل إلى المحاكي."
    fi
fi

# ============================================================
# الطبقة الثانية: محاكي عربي احتياطي بلغة Python3
# هذا ليس الهدف النهائي، بل وسيلة اختبار داخل الرمل.
# ============================================================

if command -v python3 >/dev/null 2>&1; then
    info info "أستخدم محاكي Python3 العربي..."

    python3 - <<'PY'
# -*- coding: utf-8 -*-

import sys

# ============================================================
# ذاكرة.نظام + ذاكرة.ساحة
# ذاكرة وهمية صغيرة تحاكي Arena Allocator
# ============================================================

سعة_الذاكرة = 4096
ذاكرة = bytearray(سعة_الذاكرة)
رأس_الذاكرة = 0

def ذاكرة_خصص(حجم, محاذاة=8):
    global رأس_الذاكرة

    رأس_الذاكرة = (رأس_الذاكرة + محاذاة - 1) & ~(محاذاة - 1)
    بداية = رأس_الذاكرة
    رأس_الذاكرة += حجم

    if رأس_الذاكرة > سعة_الذاكرة:
        raise MemoryError("نفدت ذاكرة المحاكي")

    return بداية

# نخصص مكانًا لطباعة النتيجة
عنوان_النتيجة = ذاكرة_خصص(32)

# ============================================================
# نظام.اكتب
# ============================================================

def نظام_اكتب(واصف, بيانات):
    if واصف == 1:
        sys.stdout.buffer.write(بيانات)
        return len(بيانات)

    if واصف == 2:
        sys.stderr.buffer.write(بيانات)
        return len(بيانات)

    return -1

# ============================================================
# نص.إلى_بايتات
# ============================================================

def نص_إلى_بايتات(نص):
    return نص.encode("utf-8")

# ============================================================
# ذاكرة.اكتب / ذاكرة.اقرأ
# ============================================================

def ذاكرة_اكتب_بايتات(عنوان, بايتات):
    ذاكرة[عنوان:عنوان + len(بايتات)] = بايتات

def ذاكرة_اقرأ_بايتات(عنوان, طول):
    return bytes(ذاكرة[عنوان:عنوان + طول])

# ============================================================
# عدد.إلى_نص
# ============================================================

def عدد_إلى_نص(قيمة):
    if قيمة == 0:
        return "0"

    سالب = False

    if قيمة < 0:
        سالب = True
        قيمة = -قيمة

    حرف = []

    while قيمة > 0:
        حرف.append(chr(ord("0") + (قيمة % 10)))
        قيمة //= 10

    if سالب:
        حرف.append("-")

    حرف.reverse()
    return "".join(حرف)

# ============================================================
# كتابة عدد داخل الذاكرة ثم إرجاع طوله
# ============================================================

def اكتب_عدد_في_الذاكرة(قيمة, عنوان):
    نص = عدد_إلى_نص(قيمة) + "\n"
    بايتات = نص_إلى_بايتات(نص)
    ذاكرة_اكتب_بايتات(عنوان, بايتات)
    return len(بايتات)

# ============================================================
# آلة.شغل
# آلة افتراضية عربية بسيطة
# ============================================================

سجلات = {}

def آلة_شغل(برنامج):
    for تعليمة in برنامج:
        الأمر = تعليمة[0]

        if الأمر == "اطبع":
            نظام_اكتب(1, نص_إلى_بايتات(تعليمة[1] + "\n"))

        elif الأمر == "حرك":
            سجلات[تعليمة[1]] = تعليمة[2]

        elif الأمر == "أضف":
            سجلات[تعليمة[1]] = سجلات[تعليمة[2]] + سجلات[تعليمة[3]]

        elif الأمر == "اطبع_عدد":
            طول = اكتب_عدد_في_الذاكرة(سجلات[تعليمة[1]], عنوان_النتيجة)
            نظام_اكتب(1, ذاكرة_اقرأ_بايتات(عنوان_النتيجة, طول))

        else:
            raise RuntimeError("أمر غير معروف: " + str(الأمر))

# ============================================================
# أول برنامج عربي
# ============================================================

برنامج = [
    ("اطبع", "سلام"),
    ("حرك", "س", 2),
    ("حرك", "ص", 3),
    ("أضف", "ن", "س", "ص"),
    ("اطبع_عدد", "ن"),
]

آلة_شغل(برنامج)
sys.stdout.buffer.flush()
PY

    exit $?
fi

# ============================================================
# الطبقة الثالثة: حل بدائي جدًا إن لم يوجد Assembly ولا Python
# ============================================================

info warn "لا يوجد as/ld ولا python3، سأستخدم printf في الصدفة كآخر حل."

# سلام\n ثم 5\n بالبايتات UTF-8
printf '\330\263\331\204\330\247\331\205\n5\n'
exit 0