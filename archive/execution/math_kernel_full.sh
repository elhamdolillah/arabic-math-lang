        for عنصر in ع:
            بيئة[ب[1]]=عنصر; نفذ(ب[3],بيئة,خرج)
        return
    if ن=="طالما":
        while قيم(ب[1],بيئة): نفذ(ب[2],بيئة,خرج)
        return
    raise Exception("بيان غير معروف")

