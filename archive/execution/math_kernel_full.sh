def قيم(ت,ب):
    ن=ت[0]
    if ن=="عدد": return ت[1]
    if ن=="نص": return ت[1]
    if ن=="قائمة":
        ع=[]
        for عنصر in ت[1]: ع.append(قيم(عنصر,ب))
        return ع
    if ن=="متغير":
        ق=ب.get(ت[1])
        if ق is None: raise Exception("غير معرف: "+ت[1])
        return ق
    if ن=="دالة": return ("إغلاق",ت[1],ت[2],ب)
    if ن=="استدعاء":
        د=ب.get(ت[1])
        if د is None: raise Exception("غير معرف: "+ت[1])
        وس=[]
        for و in ت[2]: وس.append(قيم(و,ب))
        if type(د) is tuple and د[0]=="إغلاق":
            محلي=dict(د[3]); محلي[د[1]]=وس[0]
            return قيم(د[2],محلي)
        if callable(د): return د(وس)
        raise Exception("غير قابلة للاستدعاء")
    if ن=="ثنائية":
        ي=قيم(ت[2],ب); م=قيم(ت[3],ب)
        ع=ت[1]
        if ع=="+": return ي+م
        if ع=="-": return ي-م
        if ع=="·": return ي*م
        if ع=="⊕": return ي+م
        if ع=="<": return ي<م
        if ع==">": return ي>م
        if ع=="=": return ي==م
        if ع=="≠": return ي!=م
    raise Exception("تعبير غير معروف")

def نفذ(ب,بيئة,خرج):
