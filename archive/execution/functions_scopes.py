# -*- coding: utf-8 -*-
import sys

# ============================================================
# ١. الأنواع الأساسية
# ============================================================
class نوع:
    صحيح = "صحيح"
    نص = "نص"
    فراغ = "فراغ"

# ============================================================
# ٢. عقود العمليات الموحدة
# ============================================================
عقود_العمليات = {
    "أضف": (نوع.صحيح, نوع.صحيح, نوع.صحيح),
    "اطرح": (نوع.صحيح, نوع.صحيح, نوع.صحيح),
    "اضرب": (نوع.صحيح, نوع.صحيح, نوع.صحيح),
    "ألصق": (نوع.نص, نوع.نص, نوع.نص),
}

# بيئة الأنواع الشاملة (تحفظ المتغيرات العمومية وتواقيع الدوال)
بيئة_الأنواع = {}

# ============================================================
# ٣. استثناء الإرجاع (آلية كسر التدفق والعودة من الدالة)
# ============================================================
class استثناء_ارجاع(Exception):
    def __init__(self, قيمة):
        self.قيمة = قيمة

# ============================================================
# ٤. مدقق الأنواع (Type Verifier) مع دعم الدوال والنطاقات
# ============================================================
def دقق_تعبير(تعبير, نطاق_محلي):
    الرأس = تعبير[0]
    
    if الرأس == "قيمة_صحيحة": return نوع.صحيح
    if الرأس == "قيمة_نصية": return نوع.نص
    
    if الرأس == "متغير":
        اسم = تعبير[1]
        # البحث في النطاق المحلي أولاً (Lexical Scoping)
        if اسم in نطاق_محلي: return نطاق_محلي[اسم]
        if اسم in بيئة_الأنواع and "نوع" in بيئة_الأنواع[اسم]: return بيئة_الأنواع[اسم]["نوع"]
        raise Exception(f"خطأ دلالي: المتغير '{اسم}' غير معرف.")
        
    if الرأس in عقود_العمليات:
        يسار_نوع = دقق_تعبير(تعبير[1], نطاق_محلي)
        يمين_نوع = دقق_تعبير(تعبير[2], نطاق_محلي)
        عقد = عقود_العمليات[الرأس]
        if يسار_نوع != عقد[0] or يمين_نوع != عقد[1]:
            raise Exception(f"خطأ في الأنواع: العملية '{الرأس}' تتطلب ({عقد[0]}, {عقد[1]}) ولكن تلقت ({يسار_نوع}, {يمين_نوع}).")
        return عقد[2]
        
    if الرأس == "استدع":
        اسم_الدالة = تعبير[1]
        وسائط = تعبير[2]
        if اسم_الدالة not in بيئة_الأنواع or "دالة" not in بيئة_الأنواع[اسم_الدالة]:
            raise Exception(f"خطأ: الدالة '{اسم_الدالة}' غير معرفة.")
        
        توقيع = بيئة_الأنواع[اسم_الدالة]["دالة"]
        if len(وسائط) != len(توقيع["وسائط"]):
            raise Exception(f"خطأ: عدد الوسائط في '{اسم_الدالة}' غير مطابق.")
            
        for i, وسيط in enumerate(وسائط):
            نوع_الوسيط = دقق_تعبير(وسيط, نطاق_محلي)
            if نوع_الوسيط != توقيع["وسائط"][i]:
                raise Exception(f"خطأ في أنواع وسائط الدالة '{اسم_الدالة}'.")
                
        return توقيع["ارجاع"]

    raise Exception(f"تعبير غير معروف: {الرأس}")

def دقق_بيان(بيان, نطاق_محلي, نوع_الارجاع_المتوقع=None):
    الرأس = بيان[0]
    
    if الرأس == "عرف_دالة":
        اسم = بيان[1]
        وسائط = بيان[2] # [("اسم", نوع), ...]
        نوع_الارجاع = بيان[3]
        جسم = بيان[4]
        
        # تسجيل توقيع الدالة في البيئة الشاملة
        بيئة_الأنواع[اسم] = {
            "دالة": {
                "وسائط": [ن for _, ن in وسائط],
                "ارجاع": نوع_الارجاع
            }
        }
        
        # إنشاء نطاق محلي معزول للدالة
        نطاق_الدالة = {اسم_وسيط: نوع_وسيط for اسم_وسيط, نوع_وسيط in وسائط}
        
        # تدقيق جسم الدالة مع تمرير نوع الإرجاع المتوقع للتحقق منه
        for ب in جسم:
            دقق_بيان(ب, نطاق_الدالة, نوع_الارجاع)
        return نوع.فراغ

    if الرأس == "اسند":
        اسم = بيان[1]
        تعبير = بيان[2]
        نوع_التعبير = دقق_تعبير(تعبير, نطاق_محلي)
        نطاق_محلي[اسم] = نوع_التعبير
        return نوع.فراغ
        
    if الرأس == "اطبع":
        دقق_تعبير(بيان[1], نطاق_محلي)
        return نوع.فراغ
        
    if الرأس == "ارجع":
        if نوع_الارجاع_المتوقع is None:
            raise Exception("خطأ: استخدام 'ارجع' خارج دالة.")
        نوع_القيمة = دقق_تعبير(بيان[1], نطاق_محلي)
        if نوع_القيمة != نوع_الارجاع_المتوقع:
            raise Exception(f"خطأ: نوع الإرجاع لا يطابق توقيع الدالة.")
        return نوع.فراغ

    raise Exception(f"بيان غير معروف: {الرأس}")

def دقق_برنامج(برنامج):
    print("--- بدء تدقيق الأنواع (Type Checking) ---")
    for بيان in برنامج:
        دقق_بيان(بيان, {})
    print("✅ نجح تدقيق الأنواع. الشفرة آمنة للتنفيذ.")

# ============================================================
# ٥. الآلة الافتراضية (VM) مع دعم النطاقات ومكدس الاستدعاء
# ============================================================
الآلة_الدوال = {}

def قيم(تعبير, بيئة):
    الرأس = تعبير[0]
    if الرأس == "قيمة_صحيحة": return تعبير[1]
    if الرأس == "قيمة_نصية": return تعبير[1]
    if الرأس == "متغير": return بيئة[تعبير[1]]
    
    if الرأس in عقود_العمليات:
        يسار = قيم(تعبير[1], بيئة)
        يمين = قيم(تعبير[2], بيئة)
        if الرأس == "أضف": return يسار + يمين
        if الرأس == "اطرح": return يسار - يمين
        if الرأس == "اضرب": return يسار * يمين
        if الرأس == "ألصق": return يسار + يمين
        
    if الرأس == "استدع":
        اسم_الدالة = تعبير[1]
        وسائط = [قيم(و, بيئة) for و in تعبير[2]]
        
        if اسم_الدالة in الآلة_الدوال:
            دالة = الآلة_الدوال[اسم_الدالة]
            # إنشاء نطاق محلي جديد ومعزول تماماً للدالة
            بيئة_محلية = {}
            for i, اسم_وسيط in enumerate(دالة["وسائط"]):
                بيئة_محلية[اسم_وسيط] = وسائط[i]
            
            try:
                for ب in دالة["جسم"]:
                    نفذ_بيان(ب, بيئة_محلية)
            except استثناء_ارجاع as ر:
                return ر.قيمة
            return None 
            
        raise Exception(f"الدالة {اسم_الدالة} غير موجودة في الآلة.")

    raise Exception(f"تعبير غير معروف: {الرأس}")

def نفذ_بيان(بيان, بيئة):
    الرأس = بيان[0]
    
    if الرأس == "عرف_دالة":
        اسم = بيان[1]
        وسائط = [اسم for اسم, _ in بيان[2]]
        جسم = بيان[4]
        الآلة_الدوال[اسم] = {"وسائط": وسائط, "جسم": جسم}
        return
        
    if الرأس == "اسند":
        بيئة[بيان[1]] = قيم(بيان[2], بيئة)
        return
        
    if الرأس == "اطبع":
        sys.stdout.write(str(قيم(بيان[1], بيئة)) + "\n")
        return
        
    if الرأس == "ارجع":
        raise استثناء_ارجاع(قيم(بيان[1], بيئة))

    raise Exception(f"بيان غير معروف: {الرأس}")

def نفذ_برنامج(برنامج):
    print("--- بدء التنفيذ على الآلة الافتراضية ---")
    بيئة_عمومية = {}
    for بيان in برنامج:
        نفذ_بيان(بيان, بيئة_عمومية)

