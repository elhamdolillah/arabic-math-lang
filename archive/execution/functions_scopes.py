    # تعريف دالة تربيع (تقبل صحيح وترجع صحيح)
    ("عرف_دالة", "تربيع", [("س", نوع.صحيح)], نوع.صحيح, [
        ("ارجع", ("اضرب", ("متغير", "س"), ("متغير", "س")))
    ]),
    
    # تعريف دالة ترحيب (تقبل نص وترجع نص)
    ("عرف_دالة", "رحب", [("اسم", نوع.نص)], نوع.نص, [
        ("ارجع", ("ألصق", ("قيمة_نصية", "مرحباً "), ("متغير", "اسم")))
    ]),
    
    # استخدام الدوال
    ("اسند", "ن", ("استدع", "تربيع", [("قيمة_صحيحة", 5)])),
    ("اطبع", ("متغير", "ن")), # يجب أن يطبع 25
    
