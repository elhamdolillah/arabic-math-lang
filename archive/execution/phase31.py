#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
المرحلة 31: المصفوفات متعددة الأبعاد (صف)
الدستور: ﴿والصافات صفاً﴾
"""
import sys, subprocess
sys.path.insert(0, '.')
from math_complete import *

# ═══════════════════════════════════════════════════════════
print("=" * 70)
print("المرحلة 31: المصفوفات (صف)")
print("الدستور: ﴿والصافات صفاً﴾")
print("=" * 70)

failed = 0

# ─────────────────────────────────────────────────────────
# اختبار 1: إنشاء مصفوفة 2×2 + عمليات أساسية
# ─────────────────────────────────────────────────────────
print("\n🧪 اختبار 1: إنشاء مصفوفة 2×2 (﴿والصافات صفاً﴾)")
برنامج_إنشاء = """صف١ ≔ ⟨1, 2⟩
صف٢ ≔ ⟨3, 4⟩
⎕ "الصف الأول: " ⊕ نص(رأس(صف١)) ⊕ ", " ⊕ نص(رأس(ذيل(صف١)))
⎕ "الصف الثاني: " ⊕ نص(رأس(صف٢)) ⊕ ", " ⊕ نص(رأس(ذيل(صف٢)))
⎕ "مجموع الصف الأول: " ⊕ نص(مجموع_قائمة(صف١))
⎕ "مجموع الصف الثاني: " ⊕ نص(مجموع_قائمة(صف٢))
⎕ "مجموع المصفوفة: " ⊕ نص(مجموع_قائمة(صف١) + مجموع_قائمة(صف٢))
"""

ر = حلل_رموز(برنامج_إنشاء)
ب = حلل_برنامج(ر)
asm = compile_program(ب)
with open('mat1.asm', 'w') as f:
    f.write(asm)
subprocess.run(['nasm', '-f', 'elf64', 'mat1.asm', '-o', 'mat1.o'], check=True)
subprocess.run(['ld', 'mat1.o', '-o', 'mat1'], check=True)
result = subprocess.run(['./mat1'], capture_output=True, text=True)
out = result.stdout.strip()
print(f"  الخرج:\n{out}")

if "مجموع المصفوفة: 10" in out:
    print("  ✅ إنشاء مصفوفة يعمل!")
else:
    print("  ❌ فشل")
    failed += 1

# ─────────────────────────────────────────────────────────
# اختبار 2: جمع مصفوفتين (عنصر بعنصر)
# ─────────────────────────────────────────────────────────
print("\n🧪 اختبار 2: جمع مصفوفتين (﴿وجمعناهم جمعاً﴾)")
برنامج_جمع = """صف١_أ ≔ ⟨1, 2⟩
صف٢_أ ≔ ⟨3, 4⟩
صف١_ب ≔ ⟨5, 6⟩
صف٢_ب ≔ ⟨7, 8⟩
ن١_١ ≔ رأس(صف١_أ) + رأس(صف١_ب)
ن١_٢ ≔ رأس(ذيل(صف١_أ)) + رأس(ذيل(صف١_ب))
ن٢_١ ≔ رأس(صف٢_أ) + رأس(صف٢_ب)
ن٢_٢ ≔ رأس(ذيل(صف٢_أ)) + رأس(ذيل(صف٢_ب))
⎕ "النتيجة [1,1]: " ⊕ نص(ن١_١)
⎕ "النتيجة [1,2]: " ⊕ نص(ن١_٢)
⎕ "النتيجة [2,1]: " ⊕ نص(ن٢_١)
⎕ "النتيجة [2,2]: " ⊕ نص(ن٢_٢)
"""

ر = حلل_رموز(برنامج_جمع)
ب = حلل_برنامج(ر)
asm = compile_program(ب)
with open('mat2.asm', 'w') as f:
    f.write(asm)
subprocess.run(['nasm', '-f', 'elf64', 'mat2.asm', '-o', 'mat2.o'], check=True)
subprocess.run(['ld', 'mat2.o', '-o', 'mat2'], check=True)
result = subprocess.run(['./mat2'], capture_output=True, text=True)
out = result.stdout.strip()
print(f"  الخرج:\n{out}")

if "النتيجة [1,1]: 6" in out and "النتيجة [1,2]: 8" in out and "النتيجة [2,1]: 10" in out and "النتيجة [2,2]: 12" in out:
    print("  ✅ جمع المصفوفات يعمل!")
else:
    print("  ❌ فشل")
    failed += 1

# ─────────────────────────────────────────────────────────
# اختبار 3: ضرب مصفوفة في عدد (scalar)
# ─────────────────────────────────────────────────────────
print("\n🧪 اختبار 3: ضرب في عدد (﴿يضعفها له أضعافاً كثيرة﴾)")
برنامج_ضرب = """صف١ ≔ ⟨1, 2⟩
صف٢ ≔ ⟨3, 4⟩
معامل ≔ 3
ن١_١ ≔ رأس(صف١) · معامل
ن١_٢ ≔ رأس(ذيل(صف١)) · معامل
ن٢_١ ≔ رأس(صف٢) · معامل
ن٢_٢ ≔ رأس(ذيل(صف٢)) · معامل
⎕ "3 × المصفوفة:"
⎕ "  [" ⊕ نص(ن١_١) ⊕ ", " ⊕ نص(ن١_٢) ⊕ "]"
⎕ "  [" ⊕ نص(ن٢_١) ⊕ ", " ⊕ نص(ن٢_٢) ⊕ "]"
"""

ر = حلل_رموز(برنامج_ضرب)
ب = حلل_برنامج(ر)
asm = compile_program(ب)
with open('mat3.asm', 'w') as f:
    f.write(asm)
subprocess.run(['nasm', '-f', 'elf64', 'mat3.asm', '-o', 'mat3.o'], check=True)
subprocess.run(['ld', 'mat3.o', '-o', 'mat3'], check=True)
result = subprocess.run(['./mat3'], capture_output=True, text=True)
out = result.stdout.strip()
print(f"  الخرج:\n{out}")

if "[3, 6]" in out and "[9, 12]" in out:
    print("  ✅ الضرب في عدد يعمل!")
else:
    print("  ❌ فشل")
    failed += 1

# ─────────────────────────────────────────────────────────
# اختبار 4: نقل المصفوفة (transpose)
# ─────────────────────────────────────────────────────────
print("\n🧪 اختبار 4: نقل المصفوفة (﴿ونقلبهم ذات اليمين وذات الشمال﴾)")
برنامج_نقل = """صف١ ≔ ⟨1, 2⟩
صف٢ ≔ ⟨3, 4⟩
نقل_١_١ ≔ رأس(صف١)
نقل_١_٢ ≔ رأس(صف٢)
نقل_٢_١ ≔ رأس(ذيل(صف١))
نقل_٢_٢ ≔ رأس(ذيل(صف٢))
⎕ "المصفوفة الأصلية:"
⎕ "  [" ⊕ نص(رأس(صف١)) ⊕ ", " ⊕ نص(رأس(ذيل(صف١))) ⊕ "]"
⎕ "  [" ⊕ نص(رأس(صف٢)) ⊕ ", " ⊕ نص(رأس(ذيل(صف٢))) ⊕ "]"
⎕ "المصفوفة المنقولة:"
⎕ "  [" ⊕ نص(نقل_١_١) ⊕ ", " ⊕ نص(نقل_١_٢) ⊕ "]"
⎕ "  [" ⊕ نص(نقل_٢_١) ⊕ ", " ⊕ نص(نقل_٢_٢) ⊕ "]"
"""

ر = حلل_رموز(برنامج_نقل)
ب = حلل_برنامج(ر)
asm = compile_program(ب)
with open('mat4.asm', 'w') as f:
    f.write(asm)
subprocess.run(['nasm', '-f', 'elf64', 'mat4.asm', '-o', 'mat4.o'], check=True)
subprocess.run(['ld', 'mat4.o', '-o', 'mat4'], check=True)
result = subprocess.run(['./mat4'], capture_output=True, text=True)
out = result.stdout.strip()
print(f"  الخرج:\n{out}")

# الأصلية: [1,2; 3,4] → المنقولة: [1,3; 2,4]
if "[1, 3]" in out and "[2, 4]" in out:
    print("  ✅ نقل المصفوفة يعمل!")
else:
    print("  ❌ فشل")
    failed += 1

# ─────────────────────────────────────────────────────────
# اختبار 5: محدد مصفوفة 2×2
# ─────────────────────────────────────────────────────────
print("\n🧪 اختبار 5: محدد المصفوفة (﴿وكل شيء عنده بمقدار﴾)")
برنامج_محدد = """أ ≔ 1
ب ≔ 2
ج ≔ 3
د ≔ 4
محدد ≔ أ · د - ب · ج
⎕ "المصفوفة: [" ⊕ نص(أ) ⊕ ", " ⊕ نص(ب) ⊕ "; " ⊕ نص(ج) ⊕ ", " ⊕ نص(د) ⊕ "]"
⎕ "المحدد: " ⊕ نص(محدد)
"""

ر = حلل_رموز(برنامج_محدد)
ب = حلل_برنامج(ر)
asm = compile_program(ب)
with open('mat5.asm', 'w') as f:
    f.write(asm)
subprocess.run(['nasm', '-f', 'elf64', 'mat5.asm', '-o', 'mat5.o'], check=True)
subprocess.run(['ld', 'mat5.o', '-o', 'mat5'], check=True)
result = subprocess.run(['./mat5'], capture_output=True, text=True)
out = result.stdout.strip()
print(f"  الخرج:\n{out}")

if "المحدد: -2" in out:
    print("  ✅ محدد المصفوفة يعمل!")
else:
    print("  ❌ فشل")
    failed += 1

# ─────────────────────────────────────────────────────────
# اختبار 6: ضرب مصفوفتين 2×2
# ─────────────────────────────────────────────────────────
print("\n🧪 اختبار 6: ضرب مصفوفتين (﴿فمن يعمل مثقال ذرة خيراً يره﴾)")
برنامج_ضرب_مصفوفات = """أ_١_١ ≔ 1
أ_١_٢ ≔ 2
أ_٢_١ ≔ 3
أ_٢_٢ ≔ 4
ب_١_١ ≔ 5
ب_١_٢ ≔ 6
ب_٢_١ ≔ 7
ب_٢_٢ ≔ 8
ن_١_١ ≔ أ_١_١ · ب_١_١ + أ_١_٢ · ب_٢_١
ن_١_٢ ≔ أ_١_١ · ب_١_٢ + أ_١_٢ · ب_٢_٢
ن_٢_١ ≔ أ_٢_١ · ب_١_١ + أ_٢_٢ · ب_٢_١
ن_٢_٢ ≔ أ_٢_١ · ب_١_٢ + أ_٢_٢ · ب_٢_٢
⎕ "أ × ب:"
⎕ "  [" ⊕ نص(ن_١_١) ⊕ ", " ⊕ نص(ن_١_٢) ⊕ "]"
⎕ "  [" ⊕ نص(ن_٢_١) ⊕ ", " ⊕ نص(ن_٢_٢) ⊕ "]"
"""

ر = حلل_رموز(برنامج_ضرب_مصفوفات)
ب = حلل_برنامج(ر)
asm = compile_program(ب)
with open('mat6.asm', 'w') as f:
    f.write(asm)
subprocess.run(['nasm', '-f', 'elf64', 'mat6.asm', '-o', 'mat6.o'], check=True)
subprocess.run(['ld', 'mat6.o', '-o', 'mat6'], check=True)
result = subprocess.run(['./mat6'], capture_output=True, text=True)
out = result.stdout.strip()
print(f"  الخرج:\n{out}")

# [1,2;3,4] × [5,6;7,8] = [19,22;43,50]
if "[19, 22]" in out and "[43, 50]" in out:
    print("  ✅ ضرب المصفوفات يعمل!")
else:
    print("  ❌ فشل")
    failed += 1

# ═══════════════════════════════════════════════════════════
# الملخص
# ═══════════════════════════════════════════════════════════
print("\n" + "=" * 70)
print("📖 الدستور القرآني المطبق:")
print("   ﴿والصافات صفاً﴾ — المصفوفة")
print("   ﴿سبع سماوات طباقاً﴾ — الأبعاد المتعددة")
print("   ﴿وجمعناهم جمعاً﴾ — جمع المصفوفات")
print("   ﴿يضعفها له أضعافاً كثيرة﴾ — الضرب في عدد")
print("   ﴿ونقلبهم ذات اليمين وذات الشمال﴾ — النقل")
print("   ﴿وكل شيء عنده بمقدار﴾ — المحدد")
print("   ﴿فمن يعمل مثقال ذرة خيراً يره﴾ — ضرب المصفوفات")

print("\n" + "=" * 70)
if failed == 0:
    print(f"🎉 المرحلة 31 نجحت!")
    print(f"   لغتنا العربية تدعم المصفوفات:")
    print(f"   - إنشاء مصفوفة 2×2")
    print(f"   - جمع مصفوفتين (عنصر بعنصر)")
    print(f"   - ضرب مصفوفة في عدد")
    print(f"   - نقل مصفوفة (transpose)")
    print(f"   - محدد مصفوفة 2×2")
    print(f"   - ضرب مصفوفتين 2×2")
    print(f"\n   الخطوة التالية: المرحلة 32 — الجبر الخطي (نقل، معكوس، محدد)")
else:
    print(f"❌ فشل {failed} اختبار")
    sys.exit(1)