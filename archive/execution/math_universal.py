def حلل_عامل(رموز, i):
    if i >= len(رموز):
        raise Exception("عامل مفقود")

    نوع, قيمة = رموز[i]

    if نوع == "عدد":
        return ("عدد", قيمة), i + 1

    if نوع == "نص":
        return ("نص", قيمة), i + 1

    if نوع == "عملية" and قيمة == "λ":
        i += 1
        if i >= len(رموز) or رموز[i][0] != "معرف":
            raise Exception("معامل مطلوب بعد λ")
        معامل = رموز[i][1]
        i += 1

        if i >= len(رموز) or رموز[i][0] != "عملية" or رموز[i][1] != ".":
            raise Exception("النقطة مطلوبة بعد معامل λ")
        i += 1

        جسم, i = حلل_تعبير(رموز, i)
        return ("دالة", معامل, جسم), i

    if نوع == "عملية" and قيمة == "⟨":
        i += 1
        عناصر = []

        if i < len(رموز) and رموز[i][0] == "عملية" and رموز[i][1] == "⟩":
            return ("قائمة", عناصر), i + 1

        while True:
            عنصر, i = حلل_تعبير(رموز, i)
            عناصر.append(عنصر)

            if i >= len(رموز):
                raise Exception("⟩ مطلوبة")

            if رموز[i][0] == "عملية" and رموز[i][1] == ",":
                i += 1
                continue

            if رموز[i][0] == "عملية" and رموز[i][1] == "⟩":
                i += 1
                break

            raise Exception("فاصلة أو ⟩ مطلوبة")

        return ("قائمة", عناصر), i

    if نوع == "عملية" and قيمة == "(":
        i += 1
        تعبير, i = حلل_تعبير(رموز, i)
        if i >= len(رموز) or رموز[i][0] != "عملية" or رموز[i][1] != ")":
            raise Exception(") مطلوبة")
        return تعبير, i + 1

    if نوع == "معرف":
        اسم = قيمة
        i += 1

        if i < len(رموز) and رموز[i][0] == "عملية" and رموز[i][1] == "(":
            i += 1
            وسائط = []

            if i < len(رموز) and رموز[i][0] == "عملية" and رموز[i][1] == ")":
                return ("استدعاء", اسم, وسائط), i + 1

            while True:
                وسيط, i = حلل_تعبير(رموز, i)
                وسائط.append(وسيط)

                if i >= len(رموز):
                    raise Exception(") مطلوبة")

                if رموز[i][0] == "عملية" and رموز[i][1] == ",":
                    i += 1
                    continue

                if رموز[i][0] == "عملية" and رموز[i][1] == ")":
                    i += 1
                    break

                raise Exception("فاصلة أو ) مطلوبة")

            return ("استدعاء", اسم, وسائط), i

        return ("متغير", اسم), i

    if نوع == "عملية" and قيمة == "-":
        i += 1
        عامل, i = حلل_عامل(رموز, i)
        return ("عملية_ثنائية", "-", ("عدد", 0), عامل), i

    raise Exception("عامل غير متوقع")


def ابحث(بيئة, اسم):
    محلي = بيئة[0]
    أب = بيئة[1]

    قيمة = محلي.get(اسم)
    if قيمة is not None:
        return قيمة

    if أب is None:
        raise Exception("متغير غير معرف: " + اسم)

    return ابحث(أب, اسم)


def موجود(بيئة, اسم):
    محلي = بيئة[0]
    أب = بيئة[1]

    if محلي.get(اسم) is not None:
        return True

    if أب is None:
        return False

    return موجود(أب, اسم)


def أسند(بيئة, اسم, قيمة):
    محلي = بيئة[0]
    أب = بيئة[1]

    if محلي.get(اسم) is not None:
        محلي[اسم] = قيمة
        return

    if أب is not None and موجود(أب, اسم):
        أسند(أب, اسم, قيمة)
        return

    محلي[اسم] = قيمة


def builtin_طول(وسائط):
    if len(وسائط) != 1:
        raise Exception("طول تتطلب وسيطًا واحدًا")

    قيمة = وسائط[0]
    if type(قيمة) is list or type(قيمة) is str:
        return len(قيمة)

    raise Exception("طول تتطلب قائمة أو نصًا")


def نفذ_عملية(op, س, ص):
    if op == "+":
        if type(س) is int and type(ص) is int:
            return س + ص
        raise Exception("العملية + تتطلب عددين")

    if op == "-":
        if type(س) is int and type(ص) is int:
            return س - ص
        raise Exception("العملية - تتطلب عددين")

    if op == "·":
        if type(س) is int and type(ص) is int:
            return س * ص
        raise Exception("العملية · تتطلب عددين")

    if op == "⊕":
        if type(س) is str and type(ص) is str:
            return س + ص
        raise Exception("العملية ⊕ تتطلب نصين")

    if op == "<":
        if type(س) is int and type(ص) is int:
            return س < ص
        raise Exception("العملية < تتطلب عددين")

    if op == ">":
        if type(س) is int and type(ص) is int:
            return س > ص
        raise Exception("العملية > تتطلب عددين")

    if op == "=":
        return س == ص

    if op == "≠":
        return س != ص

    raise Exception("عملية غير معروفة: " + op)


def قيم(تعبير, بيئة):
    نوع = تعبير[0]

    if نوع == "عدد":
        return تعبير[1]

    if نوع == "نص":
        return تعبير[1]

    if نوع == "قائمة":
        نتيجة = []
        عناصر = تعبير[1]
        i = 0
        while i < len(عناصر):
            نتيجة.append(قيم(عناصر[i], بيئة))
            i += 1
        return نتيجة

    if نوع == "متغير":
        return ابحث(بيئة, تعبير[1])

    if نوع == "دالة":
        return ("إغلاق", تعبير[1], تعبير[2], بيئة)

    if نوع == "استدعاء":
        دالة = ابحث(بيئة, تعبير[1])
        وسائط_قيم = []
        وسائط = تعبير[2]
        i = 0
        while i < len(وسائط):
            وسائط_قيم.append(قيم(وسائط[i], بيئة))
            i += 1

        if type(دالة) is tuple and len(دالة) == 4 and دالة[0] == "إغلاق":
            if len(وسائط_قيم) == 0:
                raise Exception("استدعاء الدالة بدون وسائط غير مدعوم")

            نتيجة = دالة
            i = 0
            while i < len(وسائط_قيم):
                if not (type(نتيجة) is tuple and len(نتيجة) == 4 and نتيجة[0] == "إغلاق"):
                    raise Exception("قيمة غير قابلة للاستدعاء")

                _, معامل, جسم, بيئة_الإغلاق = نتيجة
                محلي = {معامل: وسائط_قيم[i]}
                نتيجة = قيم(جسم, (محلي, بيئة_الإغلاق))
                i += 1

            return نتيجة

        if callable(دالة):
            return دالة(وسائط_قيم)

        raise Exception("قيمة غير قابلة للاستدعاء")

    if نوع == "عملية_ثنائية":
        يسار = قيم(تعبير[2], بيئة)
        يمين = قيم(تعبير[3], بيئة)
        return نفذ_عملية(تعبير[1], يسار, يمين)

    raise Exception("تعبير غير معروف")


def صحيح(قيمة):
    if قيمة is True:
        return True
    if قيمة is False:
        return False
    if قيمة is None:
        return False
    if قيمة == 0:
        return False
    if قيمة == "":
        return False
    if type(قيمة) is list and len(قيمة) == 0:
        return False
    return True


def نسق(قيمة):
    if قيمة is True:
        return "⊤"
    if قيمة is False:
        return "⊥"

    if type(قيمة) is list:
        أجزاء = []
        i = 0
        while i < len(قيمة):
            أجزاء.append(نسق(قيمة[i]))
            i += 1
        return "⟨" + ادمج(أجزاء, ", ") + "⟩"

    if type(قيمة) is tuple and len(قيمة) == 4 and قيمة[0] == "إغلاق":
        return "λ" + قيمة[1] + "…"

    return str(قيمة)


def نفذ_بيان(بيان, بيئة, مخرجات):
    نوع = بيان[0]

    if نوع == "أسند":
        أسند(بيئة, بيان[1], قيم(بيان[2], بيئة))
        return

    if نوع == "اطبع":
        مخرجات.append(نسق(قيم(بيان[1], بيئة)))
        return

    if نوع == "لكل":
        عناصر = قيم(بيان[2], بيئة)
        if type(عناصر) is not list:
            raise Exception("∀ تتطلب قائمة")

        اسم = بيان[1]
        جسم = بيان[3]
        i = 0
        while i < len(عناصر):
            أسند(بيئة, اسم, عناصر[i])
            نفذ_بيان(جسم, بيئة, مخرجات)
            i += 1
        return

    if نوع == "طالما":
        while صحيح(قيم(بيان[1], بيئة)):
            نفذ_بيان(بيان[2], بيئة, مخرجات)
        return

    raise Exception("بيان غير معروف")


def شغل(نص):
    رموز = حلل_رموز(نص)
    برنامج = حلل_برنامج(رموز)

    محلي = {}
    محلي["طول"] = builtin_طول
    بيئة = (محلي, None)

    مخرجات = []
    i = 0
    while i < len(برنامج):
        نفذ_بيان(برنامج[i], بيئة, مخرجات)
        i += 1

    return ادمج(مخرجات, "\n")


