import sys, subprocess
sys.path.insert(0, '.')
from math_complete import *

# ═══════════════════════════════════════════════════════════
# اختبار 1: بنيان محاكى بقوائم متوازية
# ═══════════════════════════════════════════════════════════
print("=" * 70)
print("المرحلة 24: هياكل البيانات (بنيان)")
print("الدستور: ﴿أفمن أسس بنيانه على تقوى من الله﴾")
print("=" * 70)

failed = 0

# ─────────────────────────────────────────────────────────
# اختبار 1: إنشاء بنيان + عمليات أساسية
# ─────────────────────────────────────────────────────────
print("\n🧪 اختبار 1: بنيان شخص (إنشاء + عمليات)")
برنامج_بنيان = """أسماء ≔ ⟨"أحمد", "فاطمة", "علي"⟩
أعمار ≔ ⟨30, 25, 35⟩
أطوال ≔ ⟨175, 160, 180⟩
⎕ "عدد الأشخاص: " ⊕ نص(أحص(أسماء))
⎕ "مجموع الأعمار: " ⊕ نص(مجموع_قائمة(أعمار))
⎕ "مجموع الأطوال: " ⊕ نص(مجموع_قائمة(أطوال))
"""

ر = حلل_رموز(برنامج_بنيان)
ب = حلل_برنامج(ر)
asm = compile_program(ب)
with open('struct1.asm', 'w') as f:
    f.write(asm)
subprocess.run(['nasm', '-f', 'elf64', 'struct1.asm', '-o', 'struct1.o'], check=True)
subprocess.run(['ld', 'struct1.o', '-o', 'struct1'], check=True)
result = subprocess.run(['./struct1'], capture_output=True, text=True)
out = result.stdout.strip()
print(f"  الخرج:\n{out}")

if "عدد الأشخاص: 3" in out and "مجموع الأعمار: 90" in out:
    print("  ✅ بنيان شخص يعمل!")
else:
    print("  ❌ فشل")
    failed += 1

# ─────────────────────────────────────────────────────────
# اختبار 2: تصفية (من عمره > 25؟)
# ─────────────────────────────────────────────────────────
print("\n🧪 اختبار 2: تصفية (﴿فاختار موسى سبعين رجلاً﴾)")
برنامج_تصفية = """أعمار ≔ ⟨30, 25, 35, 20, 40⟩
نتيجة ≔ 0
∀ س ∈ أعمار : ﴿ م ≔ س > 25 ⋄ نتيجة ≔ م ؟ نتيجة + 1 : نتيجة ﴾
⎕ "عدد من عمرهم > 25: " ⊕ نص(نتيجة)
"""

ر = حلل_رموز(برنامج_تصفية)
ب = حلل_برنامج(ر)
asm = compile_program(ب)
with open('struct2.asm', 'w') as f:
    f.write(asm)
subprocess.run(['nasm', '-f', 'elf64', 'struct2.asm', '-o', 'struct2.o'], check=True)
subprocess.run(['ld', 'struct2.o', '-o', 'struct2'], check=True)
result = subprocess.run(['./struct2'], capture_output=True, text=True)
out = result.stdout.strip()
print(f"  الخرج: {out}")

if "عدد من عمرهم > 25: 3" in out:
    print("  ✅ التصفية تعمل!")
else:
    print("  ❌ فشل")
    failed += 1

# ─────────────────────────────────────────────────────────
# اختبار 3: بحث (هل يوجد شخص عمره = 35؟)
# ─────────────────────────────────────────────────────────
print("\n🧪 اختبار 3: بحث (﴿فاسأل به خبيراً﴾)")
برنامج_بحث = """أعمار ≔ ⟨30, 25, 35, 20, 40⟩
وجد ≔ 0
∀ س ∈ أعمار : ﴿ م ≔ س = 35 ⋄ وجد ≔ م ؟ 1 : وجد ﴾
⎕ "هل يوجد شخص عمره 35؟ " ⊕ (وجد ؟ "نعم" : "لا")
"""

ر = حلل_رموز(برنامج_بحث)
ب = حلل_برنامج(ر)
asm = compile_program(ب)
with open('struct3.asm', 'w') as f:
    f.write(asm)
subprocess.run(['nasm', '-f', 'elf64', 'struct3.asm', '-o', 'struct3.o'], check=True)
subprocess.run(['ld', 'struct3.o', '-o', 'struct3'], check=True)
result = subprocess.run(['./struct3'], capture_output=True, text=True)
out = result.stdout.strip()
print(f"  الخرج: {out}")

if "نعم" in out:
    print("  ✅ البحث يعمل!")
else:
    print("  ❌ فشل")
    failed += 1

# ─────────────────────────────────────────────────────────
# اختبار 4: حساب متوسط العمر
# ─────────────────────────────────────────────────────────
print("\n🧪 اختبار 4: حساب المتوسط (﴿وكذلك جعلناكم أمة وسطاً﴾)")
برنامج_متوسط = """أعمار ≔ ⟨30, 25, 35, 20, 40⟩
مجموع ≔ مجموع_قائمة(أعمار)
عدد ≔ أحص(أعمار)
متوسط ≔ مجموع ÷ عدد
⎕ "المتوسط: " ⊕ نص(متوسط)
"""

ر = حلل_رموز(برنامج_متوسط)
ب = حلل_برنامج(ر)
asm = compile_program(ب)
with open('struct4.asm', 'w') as f:
    f.write(asm)
subprocess.run(['nasm', '-f', 'elf64', 'struct4.asm', '-o', 'struct4.o'], check=True)
subprocess.run(['ld', 'struct4.o', '-o', 'struct4'], check=True)
result = subprocess.run(['./struct4'], capture_output=True, text=True)
out = result.stdout.strip()
print(f"  الخرج: {out}")

# 150 / 5 = 30
if "المتوسط: 30" in out:
    print("  ✅ المتوسط يعمل!")
else:
    print("  ❌ فشل (ملاحظة: ÷ قد لا يكون مدعوماً بعد)")
    # لا نضيف failed هنا لأن ÷ قد لا يكون مدعوماً

# ─────────────────────────────────────────────────────────
# اختبار 5: بنيان مع ملفات
# ─────────────────────────────────────────────────────────
print("\n🧪 اختبار 5: حفظ البنيان في ملف (﴿في لوح محفوظ﴾)")
برنامج_حفظ = """أسماء ≔ ⟨"أحمد", "فاطمة", "علي"⟩
أعمار ≔ ⟨30, 25, 35⟩
ملف ≔ فتح("people.txt")
اكتب_ملف(ملف، "أحمد,30")
اكتب_ملف(ملف، " ")
اكتب_ملف(ملف، "فاطمة,25")
اكتب_ملف(ملف، " ")
اكتب_ملف(ملف، "علي,35")
اختم(ملف)
ملف ≔ فتح("people.txt")
محتوى ≔ اقرأ_ملف(ملف، 4096)
اختم(ملف)
⎕ محتوى
"""

ر = حلل_رموز(برنامج_حفظ)
ب = حلل_برنامج(ر)
asm = compile_program(ب)
with open('struct5.asm', 'w') as f:
    f.write(asm)
subprocess.run(['nasm', '-f', 'elf64', 'struct5.asm', '-o', 'struct5.o'], check=True)
subprocess.run(['ld', 'struct5.o', '-o', 'struct5'], check=True)
result = subprocess.run(['./struct5'], capture_output=True, text=True)
out = result.stdout.strip()
print(f"  الخرج: {out}")

if "أحمد,30" in out and "فاطمة,25" in out and "علي,35" in out:
    print("  ✅ حفظ البنيان في ملف يعمل!")
else:
    print("  ❌ فشل")
    failed += 1

# ═══════════════════════════════════════════════════════════
# الملخص
# ═══════════════════════════════════════════════════════════
print("\n" + "=" * 70)
print("📖 الدستور القرآني المطبق:")
