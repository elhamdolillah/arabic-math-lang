print("   ﴿فاختار موسى سبعين رجلاً﴾ — التصفية والاختيار")
print("   ﴿فاسأل به خبيراً﴾ — البحث والسؤال")
print("   ﴿وكذلك جعلناكم أمة وسطاً﴾ — المتوسط")
print("   ﴿في لوح محفوظ﴾ — الحفظ في ملفات")

print("\n" + "=" * 70)
if failed == 0:
    print(f"🎉 المرحلة 24 نجحت!")
    print(f"   لغتنا العربية تدعم هياكل البيانات (بنيان):")
    print(f"   - قوائم متوازية (أسماء، أعمار، أطوال)")
