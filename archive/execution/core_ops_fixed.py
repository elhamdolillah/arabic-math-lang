# -*- coding: utf-8 -*-
import sys

# ============================================================
# تحويل الأرقام العربية المشرقية إلى أرقام داخلية
# ============================================================
الأرقام_العربية = str.maketrans("٠١٢٣٤٥٦٧٨٩", "0123456789")

def هو_رقم(رمز):
    return رمز.translate(الأرقام_العربية).isdigit()

def إلى_رقم(رمز):
    return int(رمز.translate(الأرقام_العربية))

# ============================================================
# النواة الوحيدة لتنفيذ العمليات
# ممنوع على أي لهجة أن تعيد تنفيذ هذه العمليات.
# ============================================================
العمليات = {
    "أضف": lambda س, ص: int(س + ص),
    "اطرح": lambda س, ص: int(س - ص),
    "اضرب": lambda س, ص: int(س * ص),
}

الدوال = {
    "ضاعف": lambda س: int(س * 2),
}

# ============================================================
# اللهجات: مجرد خرائط ترجمة سطحية إلى نواة واحدة
# ============================================================
اللهجة_العربية = {
    "اسند": "اسند",
    "اطبع": "اطبع",
    "كرر": "كرر",
    "استدع": "استدع",
    "جمع": "أضف",
    "طرح": "اطرح",
    "ضرب": "اضرب",
}

اللهجة_الإنجليزية = {
    "set": "اسند",
    "print": "اطبع",
    "repeat": "كرر",
    "call": "استدع",
    "add": "أضف",
    "sub": "اطرح",
    "mul": "اضرب",
    "double": "ضاعف",
}

# ============================================================
# برنامجان بلهجتين مختلفين، لكن يجب أن يصبحا نفس الشفرة الموحدة
# ============================================================
المصدر_العربي = """
اسند س جمع ٢ ٣
اسند ص طرح ١٠ ٤
اسند ض ضرب س ص
اطبع ض
اسند ع ٠
كرر ٣ اسند ع جمع ع ١
اطبع ع
اسند ن استدع ضاعف ض
اطبع ن
"""

المصدر_الإنجليزي = """
set س add 2 3
set ص sub 10 4
set ض mul س ص
print ض
set ع 0
repeat 3 set ع add ع 1
print ع
set ن call double ض
print ن
"""

# ============================================================
# التحويل النصي إلى رموز + تطبيق خريطة اللهجة
# ============================================================
def توكن(نص, لهجة):
    return [لهجة.get(رمز, رمز) for رمز in نص.split()]

# ============================================================
# المحلل النحوي المشترك
# هو نفسه لكل اللهجات، لأنه يعمل على النواة بعد الترجمة.
# ============================================================
def حلل_تعبير(رموز, موضع):
    الرأس = رموز[موضع]

    # نداء موحد
    if الرأس == "استدع":
        اسم_الدالة = رموز[موضع + 1]
        وسيط, موضع = حلل_تعبير(رموز, موضع + 2)
        return ("استدع", اسم_الدالة, وسيط), موضع

    # عمليات حسابية موحدة
    if الرأس in العمليات:
        يسار, موضع = حلل_تعبير(رموز, موضع + 1)
        يمين, موضع = حلل_تعبير(رموز, موضع)
        return (الرأس, يسار, يمين), موضع

    # قيمة عددية
    if هو_رقم(الرأس):
        return ("قيمة", إلى_رقم(الرأس)), موضع + 1

    # متغير
    return ("متغير", الرأس), موضع + 1

def حلل_بيان(رموز, موضع):
    الرأس = رموز[موضع]

    # إسناد متغير
    if الرأس == "اسند":
        اسم = رموز[موضع + 1]
        تعبير, موضع = حلل_تعبير(رموز, موضع + 2)
        return ("اسند", اسم, تعبير), موضع

    # طباعة
    if الرأس == "اطبع":
        تعبير, موضع = حلل_تعبير(رموز, موضع + 1)
        return ("اطبع", تعبير), موضع

    # حلقة موحدة
    if الرأس == "كرر":
        عدد, موضع = حلل_تعبير(رموز, موضع + 1)
        جسم, موضع = حلل_بيان(رموز, موضع)
        return ("كرر", عدد, جسم), موضع

    raise Exception("بيان غير معروف: " + str(الرأس))

def حلل_برنامج(رموز):
    بيانات = []
    موضع = 0
    while موضع < len(رموز):
        بيان, موضع = حلل_بيان(رموز, موضع)
        بيانات.append(بيان)
    return بيانات

# ============================================================
# الآلة الواحدة: تنفيذ واحد لكل العمليات
# ============================================================
def قيم(تعبير, بيئة):
    الرأس = تعبير[0]

    if الرأس == "قيمة":
        return تعبير[1]

    if الرأس == "متغير":
        return بيئة[تعبير[1]]

    if الرأس == "استدع":
        اسم = تعبير[1]
        وسيط = قيم(تعبير[2], بيئة)
        return الدوال[اسم](وسيط)

    if الرأس in العمليات:
        يسار = قيم(تعبير[1], بيئة)
        يمين = قيم(تعبير[2], بيئة)
        return العمليات[الرأس](يسار, يمين)

    raise Exception("تعبير غير معروف: " + str(الرأس))

def نفذ_بيان(بيان, بيئة):
    الرأس = بيان[0]

    if الرأس == "اسند":
        بيئة[بيان[1]] = قيم(بيان[2], بيئة)
        return

    if الرأس == "اطبع":
        sys.stdout.write(str(قيم(بيان[1], بيئة)) + "\n")
        return

    if الرأس == "كرر":
        تكرارات = قيم(بيان[1], بيئة)
        # الكلمة المحجوزة في بايثون هي 'in' الإنجليزية
        for _ in range(تكرارات):
            نفذ_بيان(بيان[2], بيئة)
        return

    raise Exception("بيان غير معروف في التنفيذ: " + str(الرأس))

def نفذ_برنامج(برنامج):
    بيئة = {}
    # الكلمة المحجوزة في بايثون هي 'in' الإنجليزية
    for بيان in برنامج:
        نفذ_بيان(بيان, بيئة)
    return بيئة

# ============================================================
# اختبار منع التكرار:
# اللهجتان يجب أن تنتجا نفس الشفرة الموحدة تمامًا
# ============================================================
رموز_عربية = توكن(المصدر_العربي, اللهجة_العربية)
رموز_إنجليزية = توكن(المصدر_الإنجليزي, اللهجة_الإنجليزية)

برنامج_عربي = حلل_برنامج(رموز_عربية)
برنامج_إنجليزي = حلل_برنامج(رموز_إنجليزية)

print("هل الشفرة الموحدة متطابقة بين اللهجتين؟", برنامج_عربي == برنامج_إنجليزي)

if برنامج_عربي != برنامج_إنجليزي:
    print("فشل توحيد الشفرة!")
    print("العربية:", برنامج_عربي)
    print("الإنجليزية:", برنامج_إنجليزي)
    sys.exit(1)

print("--- التنفيذ عبر النواة الواحدة ---")
نفذ_برنامج(برنامج_عربي)
