# ═══════════════════════════════════════════════════════════
# القانون 3: قانون السور (المكية والمدنية)
#   سور = مكية + مدنية = 114  (الفاتحة مكية)
# ═══════════════════════════════════════════════════════════
برنامج_السور = """
مكية ≔ 86
مدنية ≔ 28
إجمالي ≔ مكية + مدنية
صح ≔ إجمالي = 114
⎕ "القانون 3: سور القرآن = " ⊕ نص(إجمالي) ⊕ " (مكية " ⊕ نص(مكية) ⊕ " + مدنية " ⊕ نص(مدنية) ⊕ ")"
⎕ "صح ≔ إجمالي = 114 → " ⊕ نص(صح)
"""
ر = حلل_رموز(برنامج_السور)
ب = حلل_برنامج(ر)
