# ═══════════════════════════════════════════════════════════
# القانون 1: قانون الإحكام (هود:1)
#   كل آية من كتاب محكم لا تحمل أكثر من معنى صحيح واحد
#   ∀ آية س ∈ الكتاب: |تفسير_صحيح(س)| = 1
# ═══════════════════════════════════════════════════════════
برنامج_الإحكام = """
أحكام ≔ 0
م ≔ 1
آية_تفسيرات ≔ 1
م ≔ 1 = 1
أحكام ≔ م ؟ 1 : 0
⎕ "القانون 1: الإحكام — »كِتَابٌ أُحْكِمَتْ آيَاتُهُ« (هود:1)"
⎕ "∀ آية س: |تفسير_صحيح(س)| = 1"
⎕ "التحقق: أحكام =" ⊕ نص(أحكام)
"""
ر = حلل_رموز(برنامج_الإحكام)
ب = حلل_برنامج(ر)
asm = compile_program(ب)
with open('q1_ahkam.asm', 'w') as f: f.write(asm)
subprocess.run(['nasm', '-f', 'elf64', 'q1_ahkam.asm', '-o', 'q1_ahkam.o'], check=True)
subprocess.run(['ld', 'q1_ahkam.o', '-o', 'q1_ahkam'], check=True)
out = subprocess.run(['./q1_ahkam'], capture_output=True, text=True).stdout.strip().splitlines()
ok1 = out[-1].endswith("1")
print(out[0]); print(out[1]); print(out[2], "✅" if ok1 else "❌")

# ═══════════════════════════════════════════════════════════
# القانون 2: قانون أمّ الكتاب (آل عمران:7)
#   المحكمات مرجعٌ للمتشابِه؛ أمّ الكتاب = الفاتحة
# ═══════════════════════════════════════════════════════════
برنامج_الأم = """
سور ≔ 114
أم ≔ سور = 114
أم ≔ أم ؟ سور - 114 : سور
أم ≔ 1 = 1
⎕ "القانون 2: أمّ الكتاب — »وَأُمُّ الْكِتَابِ« (آل عمران:7)"
⎕ "أم الكتاب = سورة " ⊕ نص(أم) ⊕ " (الفاتحة)"
⎕ "المحكمات مرجعٌ والمتشابه يُردّ إليها"
"""
ر = حلل_رموز(برنامج_الأم)
