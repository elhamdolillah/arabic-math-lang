# ═══════════════════════════════════════════════════════════
# القانون 4: قانون النسخ (البقرة:106)
#   ∀ آية ناسخة ← آية منسوخة: الناسخ يحل محل المنسوخ
# ═══════════════════════════════════════════════════════════
برنامج_النسخ = """
أحكام ≔ 0
م ≔ 1
آية_تفسيرات ≔ 1
م ≔ 1 = 1
أحكام ≔ م ؟ 1 : 0
⎕ "القانون 1: الإحكام — »كِتَابٌ أُحْكِمَتْ آيَاتُهُ« (هود:1)"
⎕ "∀ آية س: |تفسير_صحيح(س)| = 1"
⎕ "التحقق: أحكام =" ⊕ نص(أحكام)
"""
# نسخ: نموذج رياضي — زوج (ناسخ، منسوخ) عبر دالة استبدال
برنامج_النسخ2 = """
نص_قديم ≔ 0
نص_جديد ≔ 1
سجل ≔ نص_قديم
سجل ≔ نص_جديد
أثر ≔ سجل = نص_جديد
⎕ "القانون 4: النسخ — »وَإِن كُنْتُمْ فِي رَيْبٍ مِّمَّا نَزَّلْنَا عَلَى عَبْدِنَا فَأْتُوا بِسُورَةٍ مِّن مِّثْلِهِ« (البقرة:23)"
⎕ "آية ناسخة تحل محل آية منسوخة (بأمر الله): سجل =" ⊕ نص(سجل) ⊕ " → أثر =" ⊕ نص(أثر)
"""
ر = حلل_رموز(برنامج_النسخ2)
