WORK = os.path.dirname(os.path.abspath(__file__))

def compile_and_run(name, src):
    p = compile_program(حلل_برنامج(حلل_رموز(src)))
    with open(f'{WORK}/{name}.asm', 'w') as f:
        f.write(p)
    subprocess.run(['nasm', '-f', 'elf64', f'{WORK}/{name}.asm', '-o', f'{WORK}/{name}.o'], check=True)
    subprocess.run(['ld', f'{WORK}/{name}.o', '-o', f'{WORK}/{name}'], check=True)
    r = subprocess.run([f'{WORK}/{name}'], capture_output=True, text=True, timeout=10)
    return r.stdout.strip()

def test(name, src, expected):
    try:
        out = compile_and_run(name, src)
        ok = out == expected
        print(f"  [{'PASS' if ok else 'FAIL'}] {name}: {out!r}" + ("" if ok else f" (expected {expected!r})"))
        return ok
    except Exception as e:
        print(f"  [FAIL] {name}: {e}")
        import traceback; traceback.print_exc()
        return False

