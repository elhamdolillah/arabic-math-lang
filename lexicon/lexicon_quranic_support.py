from lexicon_quranic import المصطلحات_القرآنية, عدد_المصطلحات, الفئات_المتاحة

# ═══════════════════════════════════════════════════════════
# الأسماء المحظورة — لا يمكن استخدامها كأسماء بديلة
# هذه أسماء البنائات في المرحلة 44-46
# ═══════════════════════════════════════════════════════════
الأسماء_المحظورة = frozenset([
    "نقطة", "دائرة", "مستطيل", "مثلث",  # بناة ADT
    "نجاح", "فشل",                        # بناة Result
    "بعض", "لاشيء",                       # بناة Option
    "صندوق", "شكل",                       # أنواع معرفة في الاختبارات
])

def تحقق_من_التعارض(كلمة):
    """التحقق من أن الكلمة لا تتعارض مع أسماء البنائات"""
    return كلمة not in الأسماء_المحظورة

def جلب_المصطلحات_الآمنة():
    """إرجاع المصطلحات القرآنية الآمنة فقط (بدون تعارض)"""
    آمنة = []
    for عنصر in المصطلحات_القرآنية:
        if تحقق_من_التعارض(عنصر["كلمة"]):
            آمنة.append(عنصر)
    return آمنة

def بحث_مصطلح_قرآني(نص):
    """البحث عن مصطلح قرآني بالكلمة أو المعنى البرمجي"""
    نص_نظيف = نص.strip()
    for م in المصطلحات_القرآنية:
        if م["كلمة"] == نص_نظيف:
            return م
        if م["معنى_برمجي"] == نص_نظيف:
            return م
    return None

def توليد_أسماء_بديلة_آمنة():
    """
    توليد قاموس أسماء_بديلة آمن من المصطلحات القرآنية
    لا يتضمن أي اسم يتعارض مع البنائات
    """
    أسماء_آمنة = {}
    for م in جلب_المصطلحات_الآمنة():
        كلمة = م["كلمة"]
        رمز = م["رمز_مقابل"]
        # فقط أضف إذا لم يكن الاسم موجودًا بالفعل
        if كلمة not in أسماء_آمنة:
            أسماء_آمنة[كلمة] = رمز
    return أسماء_آمنة

def طباعة_المصطلحات_حسب_الفئة():
    """طباعة المصطلحات مرتبة حسب الفئة"""
    print("═" * 85)
    print("  المصطلحات القرآنية للغة العربية الرياضية")
    print("═" * 85)
    
    for فئة in الفئات_المتاحة():
        مصطلحات = المصطلحات_حسب_الفئة(فئة)
        print(f"\n📂 {فئة} ({len(مصطلحات)} مصطلح)")
        print("-" * 85)
        for م in مصطلحات:
            تعارض = "⚠️" if م["كلمة"] in الأسماء_المحظورة else "✅"
            print(f"  {تعارض} {م['كلمة']:<10} → {م['رمز_مقابل']:<8} ({م['معنى_برمجي']})")
            print(f"     {م['آية']}")
    
    print("\n" + "═" * 85)
    print(f"  الإجمالي: {عدد_المصطلحات()} مصطلح")
    print(f"  الآمن: {len(جلب_المصطلحات_الآمنة())} مصطلح")
    print("═" * 85)

