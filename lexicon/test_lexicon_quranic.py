import sys

# ═══ الاختبار 1: تحميل المصطلحات القرآنية ═══
def اختبار_تحميل_المصطلحات():
    """التأكد من تحميل المصطلحات بنجاح"""
    try:
        from lexicon_quranic import المصطلحات_القرآنية, عدد_المصطلحات
        assert المصطلحات_القرآنية is not None
        assert عدد_المصطلحات() >= 40, f"العدد {عدد_المصطلحات()} أقل من 40"
        # التحقق من الحقول الإلزامية
        for م in المصطلحات_القرآنية:
            assert "كلمة" in م
            assert "آية" in م
            assert "معنى_برمجي" in م
            assert "رمز_مقابل" in م
            assert "فئة" in م
        return True
    except Exception as e:
        print(f"  ❌ فشل: {e}")
        return False

# ═══ الاختبار 2: البحث بمصطلح قرآني ═══
def اختبار_بحث_مصطلح():
    """البحث عن مصطلحات قرآنية محددة"""
    try:
        from lexicon_quranic_support import بحث_مصطلح_قرآني
        # البحث عن "كن"
        نتيجة = بحث_مصطلح_قرآني("كن")
        assert نتيجة is not None, "لم يتم العثور على 'كن'"
        assert نتيجة["رمز_مقابل"] == "↻"
        # البحث عن "أحصى"
        نتيجة = بحث_مصطلح_قرآني("أحصى")
        assert نتيجة is not None, "لم يتم العثور على 'أحصى'"
        assert نتيجة["رمز_مقابل"] == "طول"
        return True
    except Exception as e:
        print(f"  ❌ فشل: {e}")
        return False

# ═══ الاختبار 3: عدم التعارض مع البنائات ═══
def اختبار_عدم_التعارض():
    """التأكد من أن الأسماء المحظورة لا تُستخدم"""
    try:
        from lexicon_quranic_support import الأسماء_المحظورة, تحقق_من_التعارض
        # الأسماء المحظورة يجب أن تفشل
        assert not تحقق_من_التعارض("نجاح"), "'نجاح' يجب أن يكون محظورًا"
        assert not تحقق_من_التعارض("فشل"), "'فشل' يجب أن يكون محظورًا"
        assert not تحقق_من_التعارض("بعض"), "'بعض' يجب أن يكون محظورًا"
        assert not تحقق_من_التعارض("لاشيء"), "'لاشيء' يجب أن يكون محظورًا"
        # المصطلحات القرآنية يجب أن تنجح
        assert تحقق_من_التعارض("كن"), "'كن' يجب أن يكون آمنًا"
        assert تحقق_من_التعارض("أحصى"), "'أحصى' يجب أن يكون آمنًا"
        return True
    except Exception as e:
        print(f"  ❌ فشل: {e}")
        return False

# ═══ الاختبار 4: توليد أسماء بديلة آمنة ═══
def اختبار_توليد_أسماء_آمنة():
    """التأكد من أن الأسماء المولدة آمنة"""
    try:
        from lexicon_quranic_support import توليد_أسماء_بديلة_آمنة, الأسماء_المحظورة
        أسماء = توليد_أسماء_بديلة_آمنة()
        assert len(أسماء) > 0, "لا توجد أسماء آمنة"
        # التأكد من عدم وجود أي اسم محظور
        for اسم in أسماء:
            assert اسم not in الأسماء_المحظورة, f"الاسم '{اسم}' محظور!"
        # التأكد من وجود مصطلحات قرآنية أساسية
        assert "كن" in أسماء, "'كن' غير موجود"
        assert "أحصى" in أسماء, "'أحصى' غير موجود"
        return True
    except Exception as e:
        print(f"  ❌ فشل: {e}")
        return False

# ═══ الاختبار 5: الفئات والإحصائيات ═══
def اختبار_الفئات():
    """التأكد من وجود فئات متعددة"""
    try:
        from lexicon_quranic import الفئات_المتاحة, المصطلحات_حسب_الفئة
        فئات = الفئات_المتاحة()
        assert len(فئات) >= 5, f"عدد الفئات {len(فئات)} أقل من 5"
        # التأكد من وجود الفئات الأساسية
        فئات_متوقعة = ["منطق", "عمليات", "قيم", "تحكم", "تنفيذ"]
        for فئة in فئات_متوقعة:
            assert فئة in فئات, f"الفئة '{فئة}' غير موجودة"
            مصطلحات = المصطلحات_حسب_الفئة(فئة)
            assert len(مصطلحات) > 0, f"الفئة '{فئة}' فارغة"
        return True
    except Exception as e:
        print(f"  ❌ فشل: {e}")
        return False

# ═══ التشغيل الرئيسي ═══
if __name__ == "__main__":
    الاختبارات = [
        ("تحميل المصطلحات القرآنية", اختبار_تحميل_المصطلحات),
        ("البحث بمصطلح قرآني", اختبار_بحث_مصطلح),
        ("عدم التعارض مع البنائات", اختبار_عدم_التعارض),
        ("توليد أسماء بديلة آمنة", اختبار_توليد_أسماء_آمنة),
        ("الفئات والإحصائيات", اختبار_الفئات),
    ]
    
    ناجح = 0
    إجمالي = len(الاختبارات)
    
    print("═" * 50)
    print("  اختبارات المصطلحات القرآنية")
    print("═" * 50)
    
    for اسم, دالة in الاختبارات:
        try:
            if دالة():
                print(f"  ✅ {اسم}")
                ناجح += 1
            else:
                print(f"  ❌ {اسم}")
        except Exception as e:
            print(f"  ❌ {اسم}: {e}")
    
    print("═" * 50)
    print(f"  النتيجة: {ناجح}/{إجمالي} {'✅' if ناجح == إجمالي else '❌'}")
    print("═" * 50)
    
    sys.exit(0 if ناجح == إجمالي else 1)
