def تطبيع_التشكيل(نص):
    """إزالة التشكيل والحركات من النص العربي للبحث الضبابي"""
    # نطاقات الحركات العربية: U+064B إلى U+0652 و U+0670
    نتيجة = []
    for حرف in نص:
        رمز = ord(حرف)
        if (0x064B <= رمز <= 0x0652) or رمز == 0x0670:
            continue  # تجاهل الحركات
        نتيجة.append(حرف)
    return "".join(نتيجة)

def جلب_الرموز():
    """إرجاع القاموس كاملًا"""
    return القاموس

def بحث_رمز(نص):
    """
    البحث عن رمز بالاسم العربي أو الاسم البديل
    يدعم البحث الضبابي البسيط عبر تطبيع التشكيل
    """
    نص_مطبع = تطبيع_التشكيل(نص).strip().lower()
    
    for رمز in القاموس:
        # البحث بالاسم الرئيسي
        if تطبيع_التشكيل(رمز["اسم"]).lower() == نص_مطبع:
            return رمز
        # البحث بالرمز نفسه
        if رمز["رمز"] == نص:
            return رمز
        # البحث بالأسماء البديلة
        for بديل in رمز["أسماء_بديلة"]:
            if تطبيع_التشكيل(بديل).lower() == نص_مطبع:
                return رمز
    
    return None

