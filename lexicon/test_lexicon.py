import sys

# ═══════════════════════════════════════════════════════════
# الاختبار 1: تحميل القاموس
# ═══════════════════════════════════════════════════════════
def اختبار_تحميل_القاموس():
    """التأكد من أن القاموس يُحمَّل بنجاح"""
    try:
        from lexicon import القاموس
        assert القاموس is not None
        assert len(القاموس) > 0
        # التحقق من أن كل عنصر يحتوي على الحقول الإلزامية
        for رمز in القاموس:
            assert "رمز" in رمز
            assert "اسم" in رمز
            assert "أسماء_بديلة" in رمز
            assert "نوع" in رمز
        return True
    except Exception as e:
        print(f"  ❌ فشل: {e}")
        return False

# ═══════════════════════════════════════════════════════════
# الاختبار 2: البحث باسم عربي
# ═══════════════════════════════════════════════════════════
def اختبار_بحث_باسم_عربي():
    """البحث عن رمز بالاسم العربي"""
    try:
        from lexicon_support import بحث_رمز
        # البحث عن "تعيين" يجب أن يعيد ≔
        نتيجة = بحث_رمز("تعيين")
        assert نتيجة is not None, "لم يتم العثور على 'تعيين'"
        assert نتيجة["رمز"] == "≔", f"الرمز المتوقع ≔، الفعلي: {نتيجة['رمز']}"
        # البحث عن "جمع" يجب أن يعيد +
        نتيجة = بحث_رمز("جمع")
        assert نتيجة is not None, "لم يتم العثور على 'جمع'"
        assert نتيجة["رمز"] == "+", f"الرمز المتوقع +، الفعلي: {نتيجة['رمز']}"
        return True
    except Exception as e:
        print(f"  ❌ فشل: {e}")
        return False

# ═══════════════════════════════════════════════════════════
# الاختبار 3: البحث باسم بديل
# ═══════════════════════════════════════════════════════════
def اختبار_بحث_باسم_بديل():
    """البحث عن رمز باسم بديل"""
    try:
        from lexicon_support import بحث_رمز
        # البحث عن "اسناد" (بديل لـ ≔)
        نتيجة = بحث_رمز("اسناد")
        assert نتيجة is not None, "لم يتم العثور على 'اسناد'"
        assert نتيجة["رمز"] == "≔", f"الرمز المتوقع ≔، الفعلي: {نتيجة['رمز']}"
        # البحث عن "اطبع" (بديل لـ ⎕)
        نتيجة = بحث_رمز("اطبع")
        assert نتيجة is not None, "لم يتم العثور على 'اطبع'"
        assert نتيجة["رمز"] == "⎕", f"الرمز المتوقع ⎕، الفعلي: {نتيجة['رمز']}"
        return True
    except Exception as e:
        print(f"  ❌ فشل: {e}")
        return False

# ═══════════════════════════════════════════════════════════
# الاختبار 4: تطبيع التشكيل
# ═══════════════════════════════════════════════════════════
def اختبار_تطبيع_التشكيل():
    """التأكد من أن البحث يتجاهل التشكيل"""
    try:
        from lexicon_support import بحث_رمز, تطبيع_التشكيل
        # تطبيع نص مشكّل
        assert تطبيع_التشكيل("مُحَمَّد") == "محمد"
        assert تطبيع_التشكيل("كِتَابٌ") == "كتاب"
        # البحث باسم مشكّل
        نتيجة = بحث_رمز("تَعْيِين")  # تشكيل على "تعيين"
        assert نتيجة is not None, "لم يتم العثور على 'تَعْيِين' مع التشكيل"
        assert نتيجة["رمز"] == "≔"
        return True
    except Exception as e:
        print(f"  ❌ فشل: {e}")
        return False

# ═══════════════════════════════════════════════════════════
# الاختبار 5: عدد الرموز ≥ 60
# ═══════════════════════════════════════════════════════════
def اختبار_عدد_الرموز():
    """التأكد من أن القاموس يحتوي على 60+ رمز"""
    try:
        from lexicon import عدد_الرموز_الإجمالي
        العدد = عدد_الرموز_الإجمالي()
        assert العدد >= 60, f"عدد الرموز {العدد} أقل من 60"
        return True
    except Exception as e:
        print(f"  ❌ فشل: {e}")
        return False

# ═══════════════════════════════════════════════════════════
# التشغيل الرئيسي
# ═══════════════════════════════════════════════════════════
if __name__ == "__main__":
    الاختبارات = [
        ("تحميل القاموس", اختبار_تحميل_القاموس),
        ("البحث باسم عربي", اختبار_بحث_باسم_عربي),
        ("البحث باسم بديل", اختبار_بحث_باسم_بديل),
        ("تطبيع التشكيل", اختبار_تطبيع_التشكيل),
        ("عدد الرموز ≥ 60", اختبار_عدد_الرموز),
    ]
    
    ناجح = 0
    إجمالي = len(الاختبارات)
    
    print("═" * 50)
    print("  اختبارات القاموس الموحد")
    print("═" * 50)
    
    for اسم, دالة in الاختبارات:
        try:
            if دالة():
                print(f"  ✅ {اسم}")
                ناجح += 1
            else:
                print(f"  ❌ {اسم}")
        except Exception as e:
            print(f"  ❌ {اسم}: استثناء {e}")
    
    print("═" * 50)
    if ناجح == إجمالي:
        print(f"🎉 {ناجح}/{إجمالي} ✅")
    else:
        print(f"❌ {ناجح}/{إجمالي} — فشل {إجمالي - ناجح}")
        sys.exit(1)
